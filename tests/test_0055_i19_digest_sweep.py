def _slug(s: str) -> str:
    return "".join(ch if ch.isalnum() or ch in "._[]" else "-" for ch in s)[:56].strip("-")


def _id(entry) -> str:
    """Stable across edits to the list: the row, the component and the scenario's name."""
    return f"r{entry[0]}:{_slug(entry[1])}:{entry[2]}"


def _sites_of(call) -> set:
    return {row for row, site in SITES.items() if S.at_site((b"", call[0], call[1]), site)}


def _run(entry):
    row, comp, name, fn, cv, cn, sv, sn, nf = entry
    site = SITES[row]
    ctrl = S.observe(fn, site, cv, cn, needle_from=None if nf is None else (SITES[nf], cn))
    shp = S.observe(fn, site, sv, sn, needle_from=None if nf is None else (SITES[nf], sn))
    return ctrl, shp


def _verdict(entry, ctrl, shp) -> dict:
    """The facts the assertions judge, computed from the two observations alone."""
    row, comp = entry[0], entry[1]
    rule = MAP_ROWS[(row, comp)]["rule"]
    exc = None if shp.raised is None else type(shp.raised).__name__
    found = set().union(*map(set, shp.found)) if shp.found else set()
    excused = set()
    for h, labels in zip(shp.hexes, shp.found):
        for other_h, fr in shp.carrying:
            if other_h != h:
                continue
            for r2 in _sites_of((h, fr)) - {row}:
                excused |= set(labels) & DEST[r2]          # the MAP's destinations only: a finding excuses nothing
    residual = found - DEST[row] - excused
    unmapped = []
    for h, fr in shp.carrying:
        if _sites_of((h, fr)):
            continue
        hit = [k for k, (spec, _) in UNMAPPED_SITES.items() if S.at_site((b"", h, fr), spec)]
        if not hit:
            unmapped.append(" <- ".join(q for _, q, _ in fr[:4]))
        else:
            extra = set(shp.labels_of.get(h, ())) - UNMAPPED_SITES[hit[0]][1]
            if extra:
                unmapped.append(f"{hit[0]} landed in {sorted(extra)}")
    return {"rule": rule, "control_carries": ctrl.carries, "control_reached": ctrl.reached,
            "control_raised": None if ctrl.raised is None else type(ctrl.raised).__name__,
            "shaped": (shp.carries, exc), "residual": residual, "unmapped": unmapped}


def _rule_problems(v, declared=frozenset()) -> list:
    """Looser than the map's rule: always a failure, whatever the entry's pin says, but for the destinations an
    UNDECLARED finding names (asserted exactly on their own)."""
    rule, (carried, exc) = v["rule"], v["shaped"]
    out = []
    if rule == "screened" and carried:
        out.append("screened, yet the shaped value reached the digest")
    if rule == "refused" and (carried or exc not in CREDENTIAL_REFUSALS):
        out.append(f"refused by the map, observed carried={carried} raised={exc}")
    if rule in KEPT and carried and v["residual"] - set(declared):
        out.append(f"{rule}: the digest landed outside the row's destinations: {sorted(v['residual'] - set(declared))}")
    return out


def _stricter(v) -> bool:
    """A departure from the map's text, never looser than its rule: a control that cannot carry; a kept component
    the shaped run does not carry, or that the operation refuses after hashing (any raise but `CorrectionRefused`,
    0011's COMMITTED refusal: its refusal-only plan and its digest persist, as the map's row 1 describes); a screened
    component refused rather than screened. Allowed, and only with a `MAP:` note."""
    rule, (carried, exc) = v["rule"], v["shaped"]
    return (not v["control_carries"] or (rule in KEPT and not carried)
            or (rule in KEPT and exc not in (None, "CorrectionRefused"))
            or (rule == "screened" and exc is not None))


@pytest.mark.parametrize("entry", SWEEP, ids=_id)
def test_each_component_follows_its_rule(entry):
    ctrl, shp = _run(entry)
    v = _verdict(entry, ctrl, shp)
    key = _id(entry)
    import os
    if os.environ.get("VERACIUM_I19_DUMP"):
        print(f"\nDUMP {key!r}: ({v['control_carries']}, {v['shaped'][0]}, {v['shaped'][1]!r}), "
              f"residual={sorted(v['residual'])} unmapped={v['unmapped']} rule={v['rule']}")
    want = EXPECTED[key]
    unreachable = not want[0] and len(want) > 3 and want[3].startswith("MAP: unreachable")
    assert v["control_reached"] or unreachable, f"{key}: the CONTROL never reached the site: the scenario does not drive it"
    assert not v["unmapped"], f"{key}: a carrying digest at no mapped site: {v['unmapped']}"
    declared = UNDECLARED.get((entry[0], key), set())
    assert not _rule_problems(v, declared), (key, _rule_problems(v, declared))
    assert (v["control_carries"], *v["shaped"]) == want[:3], (key, v)
    assert v["residual"] == declared, (key, "an UNDECLARED destination must occur exactly as declared", v["residual"])
    note = want[3] if len(want) > 3 else ""
    assert _stricter(v) == note.startswith("MAP:"), (key, "a departure from the map needs a MAP: note, and only a "
                                                          "departure may carry one", v, note)


