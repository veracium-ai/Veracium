def _functions(rel: str) -> set:
    tree = ast.parse((S.SRC / rel).read_text(encoding="utf-8"))
    out = set()

    def walk(node, prefix):
        for ch in ast.iter_child_nodes(node):
            if isinstance(ch, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                q = prefix + [ch.name]
                if not isinstance(ch, ast.ClassDef):
                    out.add(".".join(q))
                walk(ch, q)
            else:
                walk(ch, prefix)
    walk(tree, [])
    return out


def test_every_site_names_a_function_at_this_build():
    specs = list(SITES.values()) + [s for s, _ in UNMAPPED_SITES.values()]
    for spec in specs:
        frames = [spec[0], *spec[1], *(spec[2] if len(spec) > 2 else ())]
        for rel, q in frames:
            assert q in _functions(rel), (rel, q)


