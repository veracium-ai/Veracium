class ActivationReceipt(NamedTuple):
    """The audit store's typed CONFIRMATION of an activation (round 16, finding
    1). The wrapper requires the exact type and identity, verifies the row/event
    exist, AND compares the durable row to the authority (round 17, finding 1).
    Its `problems()` is TOTAL over every scalar (round 17, correction B)."""
    status: str              # "activated" | "duplicate"
    operation_id: str
    audit_committed: bool     # the operation row is durably written
    terminal_present: bool    # (duplicate) a terminal event already exists

    def problems(self, expected_operation_id: str) -> list:
        p = []
        if self.status not in ("activated", "duplicate"):
            p.append(f"status {self.status!r} is not activated|duplicate")
        if not (isinstance(self.operation_id, str)
                and self.operation_id == expected_operation_id):
            p.append(f"operation_id {self.operation_id!r} != "
                     f"{expected_operation_id!r}")
        if type(self.audit_committed) is not bool:
            p.append("audit_committed must be an exact bool")
        if type(self.terminal_present) is not bool:
            p.append("terminal_present must be an exact bool")
        # cross-field: an `activated` receipt is freshly written (durable) with
        # no terminal event yet (round 17, correction B).
        if self.status == "activated" and self.audit_committed is not True:
            p.append("an activated receipt must be audit_committed=True")
        if self.status == "activated" and self.terminal_present is not False:
            p.append("an activated receipt cannot already be terminal")
        return p


class TerminalReceipt(NamedTuple):
    """The audit store's typed CONFIRMATION of a terminal write (round 16,
    finding 2). The wrapper requires the exact type/identity/event, verifies the
    event landed, AND compares the durable payload to the requested one (round
    17, finding 2). Its `problems()` is TOTAL (round 17, correction B)."""
    status: str              # "recorded"
    operation_id: str
    event: str
    audit_committed: bool

    def problems(self, expected_operation_id: str, expected_event: str) -> list:
        p = []
        if self.status != "recorded":
            p.append(f"status {self.status!r} is not 'recorded'")
        if self.operation_id != expected_operation_id:
            p.append(f"operation_id {self.operation_id!r} != "
                     f"{expected_operation_id!r}")
        if self.event != expected_event:
            p.append(f"event {self.event!r} != {expected_event!r}")
        if type(self.audit_committed) is not bool:
            p.append("audit_committed must be an exact bool")
        return p


class TerminalFacts(NamedTuple):
    """One validated, immutable terminal-facts value, shared by the terminal
    record AND `MigrationAuditWriteError` (round 13, finding 5: v14's exception
    validated only the null-version rule — a strict subset of the record's
    contract — so it accepted a committed `source` and a `destination` at the
    wrong version). `store_changed`/`transaction_committed` are TRI-STATE —
    `True`, `False` or `None` (unknown) — because a rollback whose own result
    is unconfirmed leaves both GENUINELY unknown (round 13, finding 1: v14
    forced them to `False`, asserting no change for a store a failed rollback
    may have left partially migrated)."""
    outcome: str
    from_version: int
    to_version: int
    store_changed: object          # True | False | None (unknown)
    transaction_committed: object  # True | False | None (unknown)
    resulting_state: str
    resulting_version: object      # int | None

    def problems(self) -> list:
        """The COMPLETE terminal-facts contract, shared verbatim by the record
        and `MigrationAuditWriteError` (round 14, finding 1: v15 left the
        `migrated → changed+committed` rule OUTSIDE this method and never
        rejected a partial `None` pair or an unknown-state disagreement, so the
        exception carrier was still weaker than the record). TOTAL over any
        constructible value (round 14, correction A: `outcome=[]` /
        `resulting_state={}` raised a raw `TypeError` at set membership before
        the type check)."""
        p = []
        # --- types FIRST, before any hashing / set membership (correction A) --
        if not isinstance(self.outcome, str):
            p.append(f"outcome must be a string, is {type(self.outcome).__name__}")
        elif self.outcome not in OUTCOMES and \
                self.outcome not in _AUDIT_ONLY_OUTCOMES:
            p.append(f"outcome {self.outcome!r} is not a known terminal outcome")
        for f, val in (("store_changed", self.store_changed),
                       ("transaction_committed", self.transaction_committed)):
            if val is not None and val is not True and val is not False:
                p.append(f"{f} must be True, False, or None (unknown), not "
                         f"{_safe_repr(val)}")
        for f in ("from_version", "to_version"):
            if type(getattr(self, f)) is not int:
                p.append(f"{f} must be an int")
        # Round 15, correction B: the migration contract is ADJACENT single-step
        # (n → n+1); non-adjacent endpoints are impossible.
        if type(self.from_version) is int and type(self.to_version) is int \
                and not (0 <= self.from_version
                         and self.to_version == self.from_version + 1):
            p.append(f"endpoints must be adjacent: to_version "
                     f"{self.to_version} must be from_version "
                     f"{self.from_version} + 1")
        v = self.resulting_version
        if not (v is None or type(v) is int):
            p.append("resulting_version must be int | None")
        if not isinstance(self.resulting_state, str):
            p.append(f"resulting_state must be a string, is "
                     f"{type(self.resulting_state).__name__}")
            return p
        if self.resulting_state not in _RESULTING_STATES:
            p.append(f"resulting_state {self.resulting_state!r} is not a known "
                     f"state")
            return p
        if p:                              # a malformed scalar poisons the rest
            return p
        ch, co, st = self.store_changed, self.transaction_committed, \
            self.resulting_state
        # --- the COMPLETE (change, commit, state, version) tuple (finding 1) --
        # `store_changed` and `transaction_committed` are one fact observed
        # twice: they must be the SAME tri-state value. A partial `None` pair or
        # a disagreement is impossible.
        if ch != co:
            p.append("store_changed and transaction_committed must be the same "
                     "tri-state value — a disk change is exactly a commit, and "
                     "neither is known without the other")
        elif ch is None:                   # (None, None) → genuinely unknown
            if st != "unknown":
                p.append("unknown change/commit facts require resulting_state "
                         "unknown")
            if v is not None:
                p.append("unknown facts carry a null version")
        elif ch is True:                   # (True, True) → a committed change
            if st != "destination":
                p.append("a committed change leaves the store at the "
                         "destination")
            elif v != self.to_version:
                p.append(f"a committed change is at version {self.to_version}")
        else:                              # (False, False) → known unchanged
            if st == "destination" and v != self.to_version:
                p.append(f"resulting_state destination requires version "
                         f"{self.to_version}")
            elif st == "source" and v != self.from_version:
                p.append(f"resulting_state source requires version "
                         f"{self.from_version}")
            elif st in ("missing", "unaccepted", "unknown") and v is not None:
                p.append(f"resulting_state {st} requires a null version")
        # `migrated` is the ONE outcome whose effect is fixed: it MUST have
        # changed and committed (finding 1 — v15 held this rule in the record
        # validator alone, so the exception carrier accepted a no-change
        # `migrated`).
        if self.outcome == "migrated" and not (ch is True and co is True):
            p.append("a migrated operation must have changed and committed")
        # outcome ⇄ resulting_state (round 13, finding 4). An outcome with no
        # richer classification (kernel read-rejections like `foreign-shape`,
        # `locked`, `unsupported-sqlite`) leaves the migratable state
        # UNESTABLISHED — its only legal terminal state is `unknown`.
        allowed = _OUTCOME_TERMINAL_STATES.get(self.outcome,
                                               frozenset({"unknown"}))
        if st not in allowed:
            p.append(f"outcome {self.outcome!r} permits resulting_state "
                     f"{sorted(allowed)}, not {st!r}")
        return p


_EVENT_ID_RE = re.compile(r"^ev-[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-"
                          r"[89ab][0-9a-f]{3}-[0-9a-f]{12}$")
"""`event_id` grammar (round 10, correction 2; round 16, correction C: the
version-4 and RFC-variant bits are now enforced — v17 accepted the all-zeros
UUID `ev-00000000-...`, which is not a v4). `ev-<uuid4>`: a globally unique
opaque token, restart-safe, not a prose channel — same discipline as
`operation_id`."""


class AuditStorageUnavailable(Exception):
    """A retryable activation failure (round 10, finding 4): the durable audit
    store could not be reached. Distinguished from an internal
    validation/programming defect, which is `internal-error`. Round 11
    (correction A) split the commit-ambiguity: `committed` says what is
    PROVEN about the operation row.
      committed is False → the row was NOT written; nothing consumed; retry.
      committed is True  → the row WAS written (a response was lost after);
                           the authority IS consumed; a retry sees `duplicate`.
      committed is None  → genuinely unknown; the host must query the
                           operation_id before retrying.
    v11 mapped every `AuditStorageUnavailable` to "not consumed"; a lost
    response after a durable commit then wrongly invited a retry.

    Round 12, finding 3: **`committed` DEFAULTS TO `None`, not `False`.** An
    omitted fact is `unknown`, never a fabricated `False` — an adapter that
    raises without positive knowledge of the commit state must not silently
    claim the row definitely did not commit. The value is exactly
    `bool | None`."""

    def __init__(self, message: str, *, committed=None):
        if not (committed is None or type(committed) is bool):
            raise TypeError(
                f"committed must be bool | None, not "
                f"{type(committed).__name__}")
        super().__init__(message)
        self.committed = committed


def _freeze(v):
    """Deeply immutable COPY of a JSON-ish value (round 12, correction A: v13's
    `_readonly` proxied dict values but passed list values THROUGH by
    reference, so mutating the caller's original list mutated the published,
    supposedly-immutable audit row). Dicts become read-only proxies over frozen
    values; lists/tuples become tuples of frozen values; scalars pass. The copy
    severs every alias to caller-held mutable state."""
    if isinstance(v, dict):
        return types.MappingProxyType({k: _freeze(x) for k, x in v.items()})
    if isinstance(v, (list, tuple)):
        return tuple(_freeze(x) for x in v)
    return v


def _readonly(mapping) -> "types.MappingProxyType":
    """A read-only view whose values are themselves DEEPLY read-only copies
    (round 11, finding 4: v12's `AuditState` was a NamedTuple of LIVE dicts,
    exposed via `_ops`, so a caller mutated an operation's `state` to
    `terminal` and deleted its attempted event WITHOUT the single publish, its
    lock or validation; round 12, correction A: the copy must be deep, so no
    caller-held list aliases a published row)."""
    return types.MappingProxyType({k: _freeze(v) for k, v in mapping.items()})


def _operation_row_problems(row: dict) -> list:
    """Every operation-row field validated to its TYPE and grammar (round 12,
    correction A). The audit store is the enforcing reference, so its boundary
    refuses a malformed row rather than trusting upstream validation — token
    grammars, 64-hex digests, canonical timestamps, int versions, path cap."""
    problems = []

    def _token(field):
        v = row.get(field)
        if not (isinstance(v, str) and _TOKEN_RE.fullmatch(v)):
            problems.append(f"{field} is not a valid token: {_safe_repr(v)}")

    def _digest(field):
        v = row.get(field)
        if not (isinstance(v, str) and _DIGEST_RE.fullmatch(v)):
            problems.append(f"{field} is not 64 lowercase hex: {_safe_repr(v)}")

    if not (isinstance(row.get("operation_id"), str)
            and _OPERATION_RE.fullmatch(row["operation_id"])):
        problems.append(f"operation_id is not op-<uuid4>: "
                        f"{_safe_repr(row.get('operation_id'))}")
    for f in ("release_ref", "backup_ref"):
        _token(f)
    for f in ("source_digest", "output_digest", "migration_digest",
              "evidence_digest"):
        _digest(f)
    for f in ("issued_at", "expires_at", "attempted_at"):
        problems += _timestamp_problems(row.get(f), f)
    for f in ("from_version", "to_version"):
        if type(row.get(f)) is not int:      # bool is an int subclass — exclude
            problems.append(f"{f} must be an int, is "
                            f"{type(row.get(f)).__name__}")
    if type(row.get("from_version")) is int and type(row.get("to_version")) \
            is int and not (0 <= row["from_version"]
                            and row["to_version"] == row["from_version"] + 1):
        problems.append("endpoints must be adjacent: to_version == "
                        "from_version + 1 (round 15, correction B)")
    problems += _store_path_problems(row.get("store_path"))
    if row.get("state") != "attempted":
        problems.append(f"a new operation row's state must be 'attempted', "
                        f"is {_safe_repr(row.get('state'))}")
    return problems


class AuditState(NamedTuple):
    """The COMPLETE audit state as one DEEPLY-immutable value (rounds 10–11).
    Publishing a new `AuditState` is one attribute assignment; `ops`/`events`
    are read-only proxies over read-only rows, so no held reference can mutate
    any state — the single-publish invariant is the ONLY way the state
    changes. `event_ids` enforces the production table's `event_id` primary
    key (round 11, correction B: v12 keyed events by `(operation_id, event)`
    and never checked `event_id`, so a repeated generator produced two events
    with one id)."""
    ops: "types.MappingProxyType"
    events: "types.MappingProxyType"
    event_ids: frozenset
    seq: int


class DraftAuditStore:
    """The in-process reference of §5e's two-table model, with the schema,
    state machine AND semantic consistency enforced, publication a SINGLE
    mutation of a deeply-immutable value, and `event_id` uniqueness enforced.

    The whole state is one `AuditState` behind `self._state`. `activate` and
    `record_terminal` build and fully validate the next `AuditState`, then
    publish it with a single assignment — the ONLY mutation. A failure at any
    construction, validation, or on the publish itself leaves the previous
    state intact (production uses one DB transaction, §5e). Reads return
    read-only proxies, so the state machine cannot be bypassed. `activate`
    returns `duplicate` (consumed → `migration-quiescence-required`) or
    `activated`; only `AuditStorageUnavailable` is the retryable failure."""

    def __init__(self):
        self._state = AuditState(_readonly({}), _readonly({}), frozenset(), 0)
        self._lock = threading.Lock()

    @property
    def _ops(self):
        return self._state.ops          # read-only proxy over read-only rows

    @property
    def _events(self):
        return self._state.events

    def _operation_row(self, a, output_digest: str) -> dict:
        row = {"operation_id": a.operation_id, "release_ref": a.release_ref,
               "backup_ref": a.backup_ref, "store_path": a.store_path,
               "from_version": a.from_version, "to_version": a.to_version,
               "source_digest": a.source_digest, "output_digest": output_digest,
               "migration_digest": a.migration_digest,
               "evidence_digest": a.evidence_digest,
               "issued_at": a.issued_at, "expires_at": a.expires_at,
               "attempted_at": canonical_timestamp(datetime.now(timezone.utc)),
               "state": "attempted"}
        if set(row) != _AUDIT_OPERATION_FIELDS:          # raise, not assert:
            raise ValueError(                            # survives python -O
                f"operation row fields {sorted(row)} are not the complete "
                f"schema {sorted(_AUDIT_OPERATION_FIELDS)}")
        # Round 12, correction A: the audit store is the ENFORCING reference
        # state machine, so its boundary validates every field's TYPE and
        # grammar — not just the field-name set. v13 accepted `backup_ref=[]`.
        for p in _operation_row_problems(row):
            raise ValueError(f"operation row field invalid: {p}")
        return row

    def _publish(self, ops: dict, events: dict, event_ids: frozenset,
                 seq: int) -> None:
        # ONE mutation of a deeply-immutable value.
        self._state = AuditState(_readonly(ops), _readonly(events),
                                 event_ids, seq)

    def activate(self, a, output_digest: str) -> "ActivationReceipt":
        with self._lock:
            st = self._state
            if a.operation_id in st.ops:
                terminal = any(
                    ev in _TERMINAL_EVENTS
                    for (oid, ev) in st.events if oid == a.operation_id)
                return ActivationReceipt("duplicate", a.operation_id,
                                         audit_committed=True,
                                         terminal_present=terminal)
            row = self._operation_row(a, output_digest)
            event_id = f"ev-{uuid.uuid4()}"
            if not _EVENT_ID_RE.fullmatch(event_id):      # round 12, corr. B:
                raise ValueError(                         # grammar, not just
                    f"event_id {event_id!r} is not the frozen ev-<uuid4> "
                    f"grammar")                           # uniqueness
            if event_id in st.event_ids:                 # the PK constraint
                raise ValueError(f"event_id {event_id!r} is not unique")
            attempted = {"event_id": event_id,
                         "operation_id": a.operation_id,
                         "event": _ATTEMPTED_EVENT,
                         "occurred_at": row["attempted_at"]}
            self._publish(
                {**dict(st.ops), a.operation_id: row},
                {**dict(st.events), (a.operation_id, _ATTEMPTED_EVENT): attempted},
                st.event_ids | {event_id}, st.seq + 1)
            return ActivationReceipt("activated", a.operation_id,
                                     audit_committed=True, terminal_present=False)

    def _terminal_problems(self, op: dict, event: str, payload: dict) -> list:
        """Schema, types AND the EXACT per-cell contract (rounds 10–11). The
        complete contract, with `resulting_state` distinguishing observed
        store state from operation effect (round 11, finding 1):

            migrated               changed·committed·destination·to
            current (no repair)    ¬changed·¬committed·destination·to
            current (repair)       changed·committed·destination·to
            failed, rolled back    ¬changed·¬committed·source·from
            failed, post-commit    changed·committed·destination·to
            failed, no store       ¬changed·¬committed·missing·None
            failed, unobserved     ¬changed·¬committed·unknown·None

        Unifying rules: `store_changed == transaction_committed`; a change
        means the store reached the destination; `resulting_version` is the
        version for `source`/`destination` and `None` for `missing`/`unknown`."""
        if event not in _TERMINAL_EVENTS:
            return [f"{event!r} is not a terminal event"]
        if op["state"] == "terminal":
            return ["operation already has a terminal event — exactly one "
                    "is permitted"]
        # Round 15, correction C: the reference state machine is TOTAL over a
        # malformed payload — a non-mapping is a controlled schema error, never
        # a raw `TypeError` from `set(None)`.
        if not isinstance(payload, dict):
            return [f"terminal payload must be a mapping, is "
                    f"{type(payload).__name__}"]
        if set(payload) != _TERMINAL_PAYLOAD_FIELDS:
            return [f"terminal payload fields {sorted(payload)} are not "
                    f"exactly {sorted(_TERMINAL_PAYLOAD_FIELDS)}"]
        if not isinstance(payload["outcome"], str) or \
                _timestamp_problems(payload["occurred_at"], "occurred_at"):
            return ["terminal payload has a malformed field"]
        # The COMPLETE terminal-facts contract lives in one validated value,
        # shared with `MigrationAuditWriteError` (round 13, finding 5): tri-state
        # commit/change facts, state⇄version, and the outcome⇄state map.
        facts = TerminalFacts(
            payload["outcome"], op["from_version"], op["to_version"],
            payload["store_changed"], payload["transaction_committed"],
            payload["resulting_state"], payload["resulting_version"])
        problems = list(facts.problems())
        outcome = payload["outcome"]
        # Only the EVENT ⇄ outcome relationship stays outside `TerminalFacts`
        # (round 14, finding 1: the event is not a `TerminalFacts` field). Every
        # outcome/effect/state/version rule now lives in `facts.problems()`, so
        # the record and the exception share one complete contract.
        if event == "migration_completed" and outcome not in \
                ("migrated", "current"):
            problems.append(f"migration_completed permits only migrated or "
                            f"current, not {outcome!r}")
        elif event == "migration_failed" and outcome in _SUCCESS_OUTCOMES:
            problems.append(f"migration_failed cannot carry the success "
                            f"outcome {outcome!r}")
        return problems

    def record_terminal(self, operation_id: str, event: str,
                        payload: dict) -> "TerminalReceipt":
        with self._lock:
            st = self._state
            op = st.ops.get(operation_id)
            if op is None:
                raise ValueError(f"unknown operation {operation_id!r}")
            problems = self._terminal_problems(op, event, payload)
            if problems:
                raise ValueError("; ".join(problems))
            event_id = f"ev-{uuid.uuid4()}"
            if not _EVENT_ID_RE.fullmatch(event_id):      # round 12, corr. B
                raise ValueError(
                    f"event_id {event_id!r} is not the frozen ev-<uuid4> "
                    f"grammar")
            if event_id in st.event_ids:
                raise ValueError(f"event_id {event_id!r} is not unique")
            self._publish(
                {**dict(st.ops), operation_id: {**dict(op),
                                                "state": "terminal"}},
                {**dict(st.events), (operation_id, event): {
                    "event_id": event_id, "operation_id": operation_id,
                    "event": event, **payload}},
                st.event_ids | {event_id}, st.seq + 1)
            # Round 16, finding 2: a typed receipt is the ONLY proof of a durable
            # terminal write — a `None` return let a no-op sink report success.
            return TerminalReceipt("recorded", operation_id, event,
                                   audit_committed=True)


