# the older-row hooks and the two entry points (0013 §5b, §5d)

def _accepted_at(art, version: int) -> set:
    rec = art.get("schema_versions", {}).get(str(version), {})
    return {a.get("digest") for a in rec.get("accepted", [])
            if isinstance(a, dict)}


def _classify_source(art, conn, spath, found, objs, base) -> None:
    """The source must BE an accepted older manifestation before anything is
    said about migrating it — round 3 measured a stamped v1 store with an
    unauthorized extra table answering `migration-required`, which promises a
    migration path for a store that has none."""
    if sv.digest(objs, base) not in _accepted_at(art, base):
        raise sv.StoreVersionError(
            spath, found, sv.SCHEMA_VERSION, "stamped-shape-mismatch",
            diff=sv._shape_diff(objs, base))


def _refusing_hook(art):
    """Ordinary opening's older row: classify the source, then refuse.
    Ordinary opening cannot initiate migration — that is the offline boundary,
    stated as a mechanism."""
    def hook(conn, spath, found, objs, base):
        _classify_source(art, conn, spath, found, objs, base)
        raise MigrationRefused(
            "migration-required",
            f"store is schema v{base}; ordinary opening never migrates — "
            f"run the dedicated offline migration operation (§5b)")
    return hook


def _migrating_hook(art, authority, state):
    """The dedicated offline operation's older row: classify, check the
    authority, select the recorded path evidence, execute, compare the
    complete output against the record, and only then stamp. Every failure is
    a closed outcome; the kernel's transaction rolls anything partial back.

    Records `observed_version` into the wrapper's `state` the moment the
    source is CLASSIFIED under the lock, so a later rollback (`migration-failed`,
    `migration-result-mismatch`) can honestly report the source version rather
    than the wrapper guessing (round 11, finding 1)."""
    def hook(conn, spath, found, objs, base):
        _classify_source(art, conn, spath, found, objs, base)
        state["observed_version"] = base    # the source, established under lock
        step = MIGRATIONS_DRAFT.get(base)
        if step is None or step.to_version != sv.SCHEMA_VERSION:
            # Adjacent single-step only; the skipped-release planner is
            # deferred to the first spec that needs two real steps.
            raise MigrationRefused(
                "migration-required",
                f"no adjacent declared step migrates v{base} to "
                f"v{sv.SCHEMA_VERSION}")
        probs = authority_problems(authority, spath, step,
                                   sv.digest(objs, base),
                                   snapshot=(art, _DRAFT["digest"]))
        if probs:
            raise MigrationRefused("migration-quiescence-required",
                                   "; ".join(probs))
        # Consumption happened at operation entry (round 5): by the time the
        # hook runs, this authority is already spent regardless of outcome.
        reg = validate_registry(current=sv.SCHEMA_VERSION)
        if reg:
            raise MigrationRefused("migration-evidence-missing",
                                   "the migration registry is malformed: "
                                   + "; ".join(reg))
        # Source rebuildable drift is repaired at the SOURCE version before
        # hashing, so the full-manifest comparison is against the accepted
        # source manifestation, not against incidental index drift.
        if sv.drift(objs, base):
            sv._repair_drift(conn, base)
            objs = manifest(conn)
            if sv.digest(objs, base) not in _accepted_at(art, base) \
                    or sv.drift(objs, base):
                raise sv.StoreVersionError(
                    spath, found, sv.SCHEMA_VERSION, "stamped-shape-mismatch",
                    diff=sv._shape_diff(objs, base))
        rec = _select_path_record(art, base, objs, step)
        try:
            apply_migration(conn, step)
        except (sqlite3.Error, RuntimeError) as exc:
            raise MigrationRefused("migration-failed", repr(exc)) from exc
        try:
            if sv.drift(manifest(conn), step.to_version):
                sv._repair_drift(conn, step.to_version)
            out_objs = manifest(conn)
        except (sqlite3.Error, RuntimeError) as exc:
            raise MigrationRefused("migration-failed", repr(exc)) from exc
        # The recorded prospective output authorises the stamp: complete
        # manifestation, acceptance digest AND full-manifest hash must all
        # match what the evidence job recorded (round 3, finding 2).
        if not (identity(out_objs) == rec["output_manifestation"]
                and sv.digest(out_objs, step.to_version)
                == rec["output_acceptance_digest"]
                and full_manifest_hash(out_objs)
                == rec["output_full_manifest_hash"]):
            raise MigrationRefused(
                "migration-result-mismatch",
                "the executed migration did not reproduce the recorded "
                "output manifestation; nothing was stamped")
        conn.execute(f"PRAGMA user_version = {step.to_version}")
    return hook


def _select_path_record(art, base, objs, step) -> dict:
    """Selection over RECORDED evidence, by the full key round 3 froze:
    runtime build identity × source version × source acceptance digest ×
    source full-manifest hash × destination version × migration declaration
    digest. Exactly one record or the migration does not run."""
    probs = path_evidence_problems(art) + expected_path_problems(art)
    if probs:
        raise MigrationRefused("migration-evidence-missing",
                               "; ".join(probs[:4]))
    me = sv.build_identity(sv.runtime_identity())
    want = (me, base, step.to_version, sv.digest(objs, base),
            full_manifest_hash(objs), migration_declaration_digest(step))
    hits = [r for r in art["paths"]
            if _algorithm_class(r) == "current"
            and _keyable_path_record(r) and _path_key(r) == want]
    if len(hits) != 1:
        raise MigrationRefused(
            "migration-evidence-missing",
            f"{len(hits)} recorded path-evidence records match this runtime, "
            f"source and migration declaration; a migration no recorded "
            f"evidence covers must not run")
    return hits[0]


def _source_missing_hook(conn, spath, found, objs):
    """The migrate-mode new-row seam (round 6): the dedicated operation must
    NEVER create — v7 measured `migrate_store` creating and stamping a fresh
    v2 store after the attested v1 source was deleted, and doing the same
    over an empty replacement database."""
    raise MigrationRefused(
        "migration-source-missing",
        f"the store at {spath!r} is empty; the authority attests an "
        f"existing source and a backup of it — a migration never creates")


def _migration_uri(canonical: str) -> str:
    """A mode=rw SQLite URI from the canonical path: opening it FAILS rather
    than creating a file, so a nonexistent target path stays nonexistent
    (round 6's regression list). Percent-encoding goes through the
    filesystem bytes, so surrogate-escaped names round-trip."""
    import urllib.parse
    return ("file:" + urllib.parse.quote(os.fsencode(canonical)) + "?mode=rw")


def _terminal_facts(out, state) -> dict:
    """Derive the terminal payload's store facts HONESTLY (round 11 findings 1
    & 3; round 12 findings 1 & 2). Preference order:

      kernel facts (a committed planner outcome) → destination, its version;
      the path was proven ABSENT                 → missing, null;
      a store exists but is not an accepted source → unaccepted, null (round
        12, finding 2: v13 recorded `missing` for an existing, valid, empty
        SQLite database — a materially different physical state from a vanished
        file; `missing` is now reserved for a path proven absent);
      a source observed under the lock AND a rollback that RETURNED SUCCESSFULLY
        → source, its version (round 12, finding 1: v13 claimed `source` from
        `observed_version` alone, with no evidence the rollback actually
        succeeded — a rollback that itself fails leaves the store partially
        migrated, NOT at the source. Round 13, correction C: the claim is
        precisely that `ROLLBACK` returned success under the qualified SQLite
        contract — the draft does not re-open and re-hash the source
        manifestation, so it does not assert the stronger "re-established");
      otherwise (locked, unopenable, an escape before the planner published, OR
      a rollback that was not confirmed) → unknown, null."""
    # Committed facts are trusted ONLY when they were validated at publication
    # (round 17, finding 4: `committed_established`, not merely a non-null value).
    facts = state["facts"]
    if state.get("committed_established") and facts is not None \
            and _valid_open_result(facts):
        return {"store_changed": facts.store_changed,
                "transaction_committed": facts.transaction_committed,
                "resulting_version": facts.resulting_version,
                "resulting_state": "destination"}
    if out == "migration-source-missing":
        st = "missing" if state.get("source_absent") else "unaccepted"
        return {"store_changed": False, "transaction_committed": False,
                "resulting_version": None, "resulting_state": st}
    if (state["observed_version"] is not None
            and state.get("rolled_back") == "rolled-back"
            and not state.get("callback_defect")):
        return {"store_changed": False, "transaction_committed": False,
                "resulting_version": state["observed_version"],
                "resulting_state": "source"}
    # Round 15, finding 4: a store that OPENED and was READ but is not an
    # accepted source (foreign/malformed/newer) is `unaccepted`, not `unknown` —
    # it is the round-12 `unaccepted` case, and v16 collapsed it to `unknown`.
    if state.get("opened") and out in _READ_REJECTED \
            and not state.get("callback_defect"):
        return {"store_changed": False, "transaction_committed": False,
                "resulting_version": None, "resulting_state": "unaccepted"}
    # Unknown state. The change/commit facts are `None` (genuinely unknown) when
    # a rollback was ATTEMPTED and FAILED (round 13, finding 1) OR an
    # `on_committed` defect leaves us UNCERTAIN whether a commit happened (round
    # 17, finding 4: a malformed callback that may have masked a real commit must
    # not assert `False`). Otherwise (no transaction entered, a confirmed
    # rollback) the store is provably unchanged — `False`.
    if state.get("rolled_back") == "rollback-failed" \
            or state.get("callback_defect"):
        ch = co = None
    else:
        ch = co = False
    return {"store_changed": ch, "transaction_committed": co,
            "resulting_version": None, "resulting_state": "unknown"}


class _ConnectionCleanupError(Exception):
    """Internal: `conn.close()` raised after the operation's outcome was
    decided (round 13, finding 2). Mapped to `internal-error`, never
    `invalid-store` — a close defect is not invalid store bytes."""


def _read_sink_committed(exc, operation_id, terminal):
    """Read the AUDIT-write commit status from a terminal-sink failure, treating
    the exception's metadata as an UNTRUSTED seam (round 16, finding 4: v17 did
    `getattr(exc, "committed", ...)` on any exception, so a `committed` property
    that itself RAISED leaked a third raw exception after the store committed).
    Only a RECOGNIZED typed exception carries commit status, and the access is
    guarded — a missing, malformed, or exploding accessor is `None` (unknown)."""
    if isinstance(exc, AuditStorageUnavailable):
        try:
            v = exc.committed
        except BaseException:                  # a hostile/defective accessor
            return None
        return v if (v is None or type(v) is bool) else None
    # An unrecognized exception (a raw OSError from the in-process draft) carries
    # no protocol commit status: the draft reads its own state; a production
    # sink that cannot tell reports None.
    return True if (operation_id, terminal) in _AUDIT._events else False


def _fallback_terminal_facts(state, authority) -> "TerminalFacts":
    """Best-known terminal facts built ONLY from previously-frozen immutable
    state (round 17, finding 5: a fallback must NEVER re-run the failing
    derivation). If a commit was ESTABLISHED, the destination; else `unknown`
    with `None` change/commit (a defect leaves the commit state uncertain)."""
    if state.get("committed_established") and _valid_open_result(state["facts"]):
        f = state["facts"]
        return TerminalFacts("internal-error", authority.from_version,
                             authority.to_version, f.store_changed,
                             f.transaction_committed, "destination",
                             f.resulting_version)
    return TerminalFacts("internal-error", authority.from_version,
                         authority.to_version, None, None, "unknown", None)


def _durable_event_matches(durable, operation_id, event, payload) -> bool:
    """Whether the DURABLE terminal event equals the payload we REQUESTED (round
    17, finding 2: v18 checked only that SOME event existed under the key, so a
    sink could publish a different individually-valid payload)."""
    if not isinstance(durable, (dict, types.MappingProxyType)):
        return False
    if durable.get("operation_id") != operation_id or durable.get("event") != event:
        return False
    return all(durable.get(k) == payload.get(k) for k in _TERMINAL_PAYLOAD_FIELDS)


def _write_terminal(out, outcome, state, authority) -> None:
    """Write the consumed operation's one terminal event. TOTAL after
    consumption (round 17, finding 5): a defect in terminal-fact derivation,
    receipt validation, or publication becomes `MigrationAuditWriteError` (or an
    `internal-error` terminal from best frozen facts) — never a raw exception,
    and a proven commit survives. The receipt is bound to the REQUESTED payload
    (round 17, finding 2), not merely proven to exist."""
    # Round 17, finding 5: derivation is inside the boundary — a raising
    # `_terminal_facts` or an invalid `TerminalFacts` falls back to
    # `internal-error` from FROZEN facts, never re-running the failing path.
    try:
        store = _terminal_facts(out, state)
        facts = TerminalFacts(
            outcome, authority.from_version, authority.to_version,
            store["store_changed"], store["transaction_committed"],
            store["resulting_state"], store["resulting_version"])
        if facts.problems():
            raise ValueError("derived terminal facts are invalid")
    except Exception:
        facts = _fallback_terminal_facts(state, authority)
        outcome = str(facts.outcome)
        store = {"store_changed": facts.store_changed,
                 "transaction_committed": facts.transaction_committed,
                 "resulting_version": facts.resulting_version,
                 "resulting_state": facts.resulting_state}
    terminal = ("migration_completed" if outcome in ("migrated", "current")
                else "migration_failed")
    payload = {"outcome": outcome, "occurred_at":
               canonical_timestamp(datetime.now(timezone.utc)), **store}

    def _fail(exc, audit_committed):
        raise MigrationAuditWriteError(
            operation_id=authority.operation_id,
            store_path=authority.store_path, facts=facts,
            audit_committed=audit_committed, cause=exc) from exc

    try:
        receipt = _AUDIT.record_terminal(authority.operation_id, terminal,
                                         payload)
    except MigrationAuditWriteError:
        raise
    except Exception as exc:
        # Round 15 corr A + round 16 finding 4: the sink exception's commit
        # status is read only for a recognized type, under guard.
        _fail(exc, _read_sink_committed(exc, authority.operation_id, terminal))
        return
    # Round 16 f2 + round 17 f2 + corr B: the receipt is VALIDATED (every scalar)
    # AND BOUND to the durable event, which must equal the REQUESTED payload.
    rprob = (receipt.problems(authority.operation_id, terminal)
             if type(receipt) is TerminalReceipt else ["not a TerminalReceipt"])
    durable = _AUDIT._events.get((authority.operation_id, terminal))
    if rprob or durable is None or not _durable_event_matches(
            durable, authority.operation_id, terminal, payload):
        _fail(RuntimeError(
            f"terminal receipt/record does not bind the requested payload: "
            f"receipt={_safe_repr(receipt)} problems={rprob}"),
            audit_committed=(receipt.audit_committed
                             if type(receipt) is TerminalReceipt else None))


def _run(path, busy_timeout_ms: int, migrating: bool,
         authority=None) -> Outcome:
    """The terminal-audit wrapper. Once an operation is consumed EVERY ending
    writes its terminal event — a normal closed outcome, and (round 11,
    finding 3) a NAMED escape after consumption: a `PackageConsistencyError`
    is terminalized as `package-inconsistent` and re-raised, so a consumed
    operation is never left without a terminal record. `MigrationAuditWriteError`
    is the one escape NOT terminalized — it IS the terminal-write failure."""
    state = {"consumed": False, "facts": None, "observed_version": None,
             "rolled_back": None, "source_absent": False, "opened": False,
             "committed_established": False, "callback_defect": None}
    try:
        out = _run_inner(path, busy_timeout_ms, migrating, authority, state)
    except MigrationAuditWriteError:
        raise                              # the terminal write itself failed
    except sv.PackageConsistencyError:
        if migrating and state["consumed"]:
            _write_terminal("internal-error", "package-inconsistent", state,
                            authority)
        raise                              # named escape, re-raised (§5d)
    if migrating and state["consumed"]:
        _write_terminal(out, str(out), state, authority)
    return out


def _run_inner(path, busy_timeout_ms: int, migrating: bool,
               authority, state) -> Outcome:
    # THE outermost boundary (rounds 5-7): parameter validation, path
    # conversion, canonicalization, the evidence SNAPSHOT, authority
    # validation, context entry, the connection and the planner all sit
    # inside it, with filesystem-encoding-aware conversions throughout.
    # Exactly two named classes escape (PackageConsistencyError,
    # MigrationAuditWriteError); anything else unforeseen is
    # `internal-error` — round 7: labelling an internal defect
    # `invalid-store` or `migration-failed` invited hosts to remediate a
    # healthy database.
    phase = "parameter-validation"
    try:
        if type(busy_timeout_ms) is not int or \
                not 0 < busy_timeout_ms <= 600_000:
            return Outcome("invalid-request",
                           f"busy_timeout_ms must be an int in 1..600000, "
                           f"got {_safe_repr(busy_timeout_ms)}")
        try:
            fs = os.fsdecode(os.fspath(path))
        except Exception as exc:
            return Outcome("invalid-request",
                           f"path is not path-like: {_safe_repr(exc)}")
        phase = "canonicalization"
        try:
            canonical = os.path.realpath(fs)
        except Exception as exc:
            return Outcome("store-unopenable", diagnostic=_safe_repr(exc))
        if len(os.fsencode(canonical)) > 4096:
            return Outcome("store-unopenable",
                           "canonical path exceeds 4096 bytes")
        # ONE evidence snapshot for the whole operation (round 7, finding 1):
        # digest and parse are of the same bytes, the authority is compared
        # against that digest, and the SAME parsed object enters the planner
        # context — nothing re-reads the path.
        phase = "evidence-snapshot"
        snapshot = _artifact_snapshot()
        if migrating:
            phase = "authority-validation"
            probs = authority_static_problems(authority, canonical,
                                              snapshot=snapshot)
            if probs:
                return Outcome("migration-quiescence-required",
                               diagnostic="; ".join(probs))
            res = _static_resolution_problems(authority, snapshot)
            if res:
                return Outcome("migration-evidence-missing",
                               diagnostic="; ".join(res))
            record = _resolve_path_record(authority, snapshot[0])
            phase = "authority-consumption"
            try:
                _consume_authority(authority,
                                   record["output_acceptance_digest"], state)
            except MigrationRefused as e:
                # `state["consumed"]` may ALREADY be set — a committed=True
                # activation whose response was lost is durably consumed
                # (round 14, finding 2), so the wrapper still writes a terminal.
                return Outcome(e.reason, diagnostic=e.diagnostic)
            state["consumed"] = True
            # Round 13, finding 3: `os.path.lexists` returns False for a path
            # the process merely cannot SEARCH to (EACCES on a parent) — it is
            # not proof of absence. Only an explicit ENOENT is `missing`; an
            # access/other error means the store's presence is UNKNOWN, so the
            # operation refuses `store-unopenable` (never fabricates `missing`).
            try:
                os.lstat(canonical)
            except FileNotFoundError:
                state["source_absent"] = True     # PROVEN absent → the only missing
                return Outcome(
                    "migration-source-missing",
                    f"no store exists at {canonical!r}; the authority "
                    f"attests an existing source — a migration never "
                    f"creates")
            except OSError as exc:
                return Outcome(
                    "store-unopenable",
                    f"cannot determine whether a source exists at "
                    f"{canonical!r} (the path is not observable): "
                    f"{_safe_repr(exc)}")
        phase = "context-entry"
        with _draft(loaded=snapshot) as art:
            try:
                phase = "runtime-gates"
                if not sv.runtime_supported():
                    return Outcome(
                        "unsupported-sqlite",
                        f"sqlite {sqlite3.sqlite_version} has no qualified "
                        f"schema-runtime record in the draft evidence; "
                        f"regenerate it here (migrations_0013.py "
                        f"--write-evidence)")
                if migrating and not migration_runtime_supported(art):
                    return Outcome(
                        "unsupported-sqlite",
                        "this runtime has no migration-confinement "
                        "qualification (or its recorded authorizer "
                        "behaviours do not reproduce here); migration "
                        "refuses before touching the store")
                raw_hook = (_migrating_hook(art, authority, state) if migrating
                            else _refusing_hook(art))
                if migrating:
                    # Round 15, finding 3: a `sqlite3.DatabaseError` from WITHIN
                    # the migration hook is a migration failure, not the planner
                    # reading invalid store bytes — convert it here so it never
                    # reaches the `invalid-store` classification below.
                    def hook(*a, _raw=raw_hook, **k):
                        try:
                            return _raw(*a, **k)
                        except sqlite3.DatabaseError as exc:
                            raise MigrationRefused(
                                "migration-failed",
                                f"migration hook: {_safe_repr(exc)}") from exc
                else:
                    hook = raw_hook
                phase = "connect"
                try:
                    if migrating:
                        conn = sqlite3.connect(_migration_uri(canonical),
                                               uri=True,
                                               timeout=busy_timeout_ms / 1000)
                    else:
                        conn = sqlite3.connect(canonical,
                                               timeout=busy_timeout_ms / 1000)
                except sqlite3.Error as exc:
                    # Round 16, finding 5: the pre-consumption `lstat` can go
                    # STALE (the source deleted between the presence check and
                    # this mode=rw open). Re-check with a FRESH exception-bearing
                    # stat — a confirmed absence is a vanished source
                    # (`migration-source-missing` / `missing`), not an
                    # unopenable path. `mode=rw` still never re-creates it.
                    if migrating:
                        try:
                            os.lstat(canonical)
                        except FileNotFoundError:
                            state["source_absent"] = True
                            return Outcome(
                                "migration-source-missing",
                                f"the source at {canonical!r} vanished between "
                                f"the presence check and the open")
                        except OSError:
                            pass       # unobservable → store-unopenable/unknown
                    return Outcome("store-unopenable",
                                   diagnostic=_safe_repr(exc))
                state["opened"] = True           # the store opened successfully
                phase = "planner"
                # Round 15, finding 5: the cleanup scope starts the INSTANT the
                # connection exists, so an `isolation_level`/PRAGMA setup failure
                # cannot leak it — every opened connection is closed exactly once.
                try:
                    conn.isolation_level = None
                    conn.execute(
                        f"PRAGMA busy_timeout = {int(busy_timeout_ms)}")
                    # on_committed publishes the OpenResult the instant a
                    # branch commits, BEFORE the kernel's post-commit cleanup
                    # (round 11, finding 2): a cleanup failure then cannot
                    # erase a proven commit. The sink is a dict setitem —
                    # infallible.
                    to_v = authority.to_version if migrating \
                        else sv.SCHEMA_VERSION
                    try:
                        label = sv.open_versioned(
                            conn, canonical,
                            allow_adopt=not migrating,  # a migration never adopts
                            older=hook,
                            new=_source_missing_hook if migrating else None,
                            # Round 17, finding 4: a VALIDATING commit sink —
                            # only a valid destination `OpenResult` establishes
                            # committed facts; a malformed publication is a defect.
                            on_committed=_make_on_committed(state, to_v),
                            on_rolled_back=lambda s:
                                state.__setitem__("rolled_back", s))
                    except sqlite3.DatabaseError as exc:
                        # `invalid-store` is ONLY the kernel reading bad bytes
                        # (round 14 f4; round 15 f3). A read defect AFTER a
                        # PROVEN commit (round 17 f4: `committed_established`, not
                        # merely `facts is not None`) is our defect, not bytes.
                        if state.get("callback_defect") \
                                or state.get("committed_established"):
                            return Outcome("internal-error",
                                           diagnostic=f"post-commit read defect: "
                                                      f"{_safe_repr(exc)}")
                        return Outcome("invalid-store",
                                       diagnostic=_safe_repr(exc))
                    # A malformed `on_committed` publication is a kernel-contract
                    # defect (round 17, finding 4).
                    if state.get("callback_defect"):
                        return Outcome(
                            "internal-error",
                            diagnostic=f"on_committed defect: "
                                       f"{state['callback_defect']}")
                    # Round 15 f2 + round 16 f3 + round 17 f3: the kernel result
                    # is a library contract — validate it COMPLETELY, mode-aware,
                    # and against the on_committed BRANCH, before trusting it.
                    rp = _open_result_problems(label, migrating, to_v,
                                               state.get("facts"))
                    if rp:
                        return Outcome(
                            "internal-error",
                            diagnostic="kernel result invalid: " + "; ".join(rp))
                    state["facts"] = label       # belt and suspenders
                    return Outcome(label)
                finally:
                    # Round 13, finding 2: closing the connection is CLEANUP,
                    # not a read of the store. A close defect must not
                    # masquerade as `invalid-store`, so it raises a distinct
                    # sentinel classified below as `internal-error`.
                    try:
                        conn.close()
                    except sqlite3.Error as exc:
                        raise _ConnectionCleanupError(_safe_repr(exc)) from exc
            except _ConnectionCleanupError as exc:
                return Outcome("internal-error",
                               diagnostic=f"connection cleanup failed after "
                                          f"the operation: {exc}")
            except sv.StoreVersionError as e:
                return Outcome(e.reason, diagnostic=e.diff)
            except MigrationRefused as e:
                return Outcome(e.reason, diagnostic=e.diagnostic)
            except sqlite3.DatabaseError as exc:
                # Round 14, finding 4: a DatabaseError reaching HERE is NOT the
                # planner reading invalid bytes (that is caught at the
                # `open_versioned` call above and mapped to `invalid-store`). It
                # came from a runtime probe, `PRAGMA` setup, or another library
                # operation — a defect in THIS library, `internal-error`, never
                # invalid store bytes on a healthy database.
                return Outcome("internal-error",
                               diagnostic=f"phase={phase}: {_safe_repr(exc)}")
    except sv.PackageConsistencyError:
        raise                        # named escape 1 (§5d)
    except MigrationAuditWriteError:
        raise                        # named escape 2 (§5e)
    except _DraftContextMismatch as exc:
        return Outcome("migration-evidence-missing" if migrating
                       else "unsupported-sqlite",
                       diagnostic=_safe_repr(exc))
    except Exception as exc:
        # Round 7, finding 5: an unforeseen failure is a defect in THIS
        # library, not a property of the store and not a migration outcome —
        # labelling it invalid-store invited hosts to restore a healthy
        # database. `internal-error` is truthful: phase named, commit state
        # unknown unless the phase proves otherwise.
        return Outcome(
            "internal-error",
            diagnostic=f"phase={phase}; commit-state="
                       f"{'false' if phase != 'planner' else 'unknown'}; "
                       f"{_safe_repr(exc)}")


def open_or_migrate(path, busy_timeout_ms: int = 5000) -> Outcome:
    """Ordinary opening: the full inherited `0007` table, and the older row
    REFUSES — `migration-required` for an accepted older source, the ordinary
    shape reasons otherwise. No authority parameter exists here: the migration
    operation is not exposed through tenant-facing opening (round 3)."""
    return _run(path, busy_timeout_ms, migrating=False)


def migrate_store(path, authority: MigrationAuthority,
                  busy_timeout_ms: int = 5000) -> Outcome:
    """The dedicated offline migration operation (§5b): same planner, with the
    older row migrating under recorded evidence and an explicit, bound,
    exact-typed host attestation."""
    return _run(path, busy_timeout_ms, migrating=True, authority=authority)


