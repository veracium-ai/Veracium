MIGRATION_FAILURES = ("migration-required", "migration-evidence-missing",
                      "migration-failed", "migration-result-mismatch",
                      "migration-quiescence-required",
                      "migration-source-missing",
                      "migration-audit-unavailable",
                      "migration-audit-state-unknown")
"""The closed failure model: hosts branch on these, plus 0007's REASONS.
Round 6 added `migration-source-missing` — the dedicated operation found no
accepted older source where its authority attests one (a vanished file, an
empty or truncated replacement, a nonexistent path; v7 CREATED a fresh v2
store there, measured) — and `migration-audit-unavailable` — the attempted
audit record is PROVEN not written, so the operation refuses before any store
access with the authority NOT consumed (§5e: the insert IS the consumption).
Round 12, finding 3 added `migration-audit-state-unknown`: the attempted-record
write neither confirmed nor disproved (a lost response) — the authority MAY be
consumed, so a retry is NOT safe until the host queries the durable
`operation_id`. It is a structurally distinct outcome from the
proven-not-written `migration-audit-unavailable`, which v13 collapsed them
into."""

STORE_FAILURES = ("invalid-store", "store-unopenable")
"""Round 4: the bytes at the path may fail before any version decision —
`invalid-store` (the file is not readable as a SQLite database, or fails at
the SQLite level while being read) and `store-unopenable` (the path cannot be
opened at all). Both were escaping as raw `DatabaseError`/`OperationalError`,
which the closed model claimed to represent and did not."""

PROTOCOL_FAILURES = ("invalid-request",)
INTERNAL_FAILURES = ("internal-error",)
"""Round 7: an unforeseen failure mapped to `invalid-store` or
`migration-failed` was a FALSE outcome — hosts remediate stores over those.
`internal-error` says what is true: a defect in this library, phase named in
the diagnostic, commit state unknown unless the phase proves otherwise."""
"""Round 5: a malformed CALL — a mistyped or out-of-range `busy_timeout_ms`,
a non-pathlike path argument — is neither a store property nor an evidence
property, and it was escaping as `TypeError` from timeout arithmetic before
any boundary. One closed member; the diagnostic says which parameter."""

OUTCOMES = (frozenset({"created", "current", "adopted", "migrated"})
            | sv.REASONS | frozenset(MIGRATION_FAILURES)
            | frozenset(STORE_FAILURES) | frozenset(PROTOCOL_FAILURES)
            | frozenset(INTERNAL_FAILURES))
"""Every value the two entry points can return. Free-form strings — round 3
measured `unexpected version 0` — are unrepresentable: `Outcome` refuses any
value outside this set."""


class Outcome(str):
    """A closed-vocabulary outcome that still `==`-compares as its string.

    Structured (round 3, finding 4): the branch value is the closed member;
    `diagnostic` carries detail for logs and bug reports and never leaks into
    the value hosts branch on."""
    __slots__ = ("diagnostic",)

    def __new__(cls, value: str, diagnostic: str | None = None):
        if value not in OUTCOMES:
            raise ValueError(f"{value!r} is not in the closed outcome "
                             f"vocabulary")
        out = str.__new__(cls, value)
        out.diagnostic = diagnostic
        return out


class MigrationRefused(Exception):
    """Internal control flow for the migration-specific closed reasons; mapped
    to an `Outcome` at the entry points, never shown to callers raw."""

    def __init__(self, reason: str, diagnostic: str | None = None):
        # raise, not assert (round 16, correction D): a load-bearing closed-
        # vocabulary check must survive `python -O`, like the operation-row guard.
        if reason not in MIGRATION_FAILURES:
            raise ValueError(f"{reason!r} is not a closed migration failure")
        self.reason, self.diagnostic = reason, diagnostic
        super().__init__(f"{reason}: {diagnostic or ''}")


class MigrationAuditWriteError(RuntimeError):
    """An audit record could not be written AFTER the operation touched or
    changed the store (round 6; §5e freezes the full state machine). Like
    `0007`'s `PostCommitAuditError` this is a deliberate, NAMED exception to
    §5d's total-Outcome claim. It carries the SAME validated `TerminalFacts`
    the terminal record would have (round 13, finding 5: v14 validated only the
    null-version rule — a subset — so it accepted a committed `source` and a
    `destination` at the wrong version). `facts.transaction_committed` says
    whether the migration happened — `True` means the store IS migrated and a
    retry opens `current`. **`False`/`None` do NOT prove the store is
    unchanged** (round 12, finding 4): `facts.resulting_state` says which of
    `missing`/`unaccepted`/`unknown`/`source`/`destination` it actually is. The
    audit failures that map to a closed outcome instead are the ATTEMPTED-record
    ones (`migration-audit-unavailable`/`migration-audit-state-unknown`),
    because nothing has happened yet. Declared here as frozen contract; the
    production sink raises it at implementation."""

    def __init__(self, operation_id: str, store_path: str,
                 facts: "TerminalFacts", *, audit_committed=None,
                 cause: BaseException | None = None):
        if not isinstance(facts, TerminalFacts):
            raise TypeError("facts must be a TerminalFacts")
        problems = facts.problems()
        if problems:
            raise ValueError("MigrationAuditWriteError given invalid terminal "
                             "facts: " + "; ".join(problems))
        if not (isinstance(operation_id, str)
                and _OPERATION_RE.fullmatch(operation_id)):
            raise ValueError(f"operation_id {operation_id!r} is not op-<uuid4>")
        # Round 14, correction B: the exception is a frozen public contract and
        # a caller decision input, so it validates its own context, not just
        # `facts` — a store_path must be a canonical absolute filesystem path
        # under the byte cap, and the endpoints must be adjacent and ordered.
        for pr in _store_path_problems(store_path):
            raise ValueError(f"store_path invalid: {pr}")
        # Endpoint adjacency is enforced by `facts.problems()` above (round 15,
        # correction B: v16's `from < to` here accepted 1 → 3).
        # Round 14, finding 3: whether the AUDIT write itself committed —
        # separate from `facts.transaction_committed` (the STORE). True = the
        # terminal record is durable though the response was lost; False =
        # definitely not written; None = unknown, query by operation_id.
        if not (audit_committed is None or type(audit_committed) is bool):
            raise TypeError("audit_committed must be True, False, or None "
                            f"(not {type(audit_committed).__name__} — round 15 "
                            f"correction B: `1` is not `True`)")
        self.operation_id = operation_id
        self.store_path = store_path
        self.facts = facts
        self.audit_committed = audit_committed
        # convenience mirrors of the load-bearing fields
        self.committed = facts.transaction_committed
        self.store_changed = facts.store_changed
        self.resulting_state = facts.resulting_state
        self.resulting_version = facts.resulting_version
        vstr = (f"v{facts.resulting_version}"
                if facts.resulting_version is not None
                else facts.resulting_state)
        super().__init__(
            f"audit write failed after the operation ran "
            f"(outcome {facts.outcome!r}, store committed="
            f"{facts.transaction_committed}, audit_committed={audit_committed}, "
            f"operation {operation_id!r}, store {store_path!r}, {vstr}); the "
            f"audit is the record of an irreversible operation and its failure "
            f"is surfaced loudly, never as migration-failed")
        self.__cause__ = cause


def _safe_repr(x) -> str:
    """Diagnostics are built from foreign objects whose __repr__ may itself
    raise (round 6, measured with a PathLike whose repr raised) — a
    diagnostic must never be the thing that breaks the boundary."""
    try:
        return repr(x)
    except Exception:
        return f"<unrepresentable {type(x).__name__}>"


_MISSING = object()   # sentinel: an exception carries no `.committed` attribute


def _valid_open_result(label) -> bool:
    """Backwards-compatible shape check (round 15, finding 2): a well-typed
    `OpenResult`. The COMPLETE, mode-aware SEMANTIC contract is
    `_open_result_problems` (round 16, finding 3)."""
    return (isinstance(label, sv.OpenResult)
            and str(label) in _SUCCESS_OUTCOMES
            and type(label.store_changed) is bool
            and type(label.transaction_committed) is bool
            and type(label.resulting_version) is int
            and label.resulting_version >= 0)


def _make_on_committed(state, to_v):
    """A VALIDATING commit sink (round 17, finding 4: v18 stored ANY object the
    kernel passed, so a malformed publication that suppressed the real one erased
    a proven commit and was still treated as `non-null` evidence). It accepts
    ONLY a valid `OpenResult` at the destination, records that valid committed
    facts were established (separately from the facts value), rejects a second
    contradictory publication, and NEVER overwrites an earlier valid receipt
    with a malformed one."""
    def sink(r):
        if not _valid_open_result(r) or str(r) not in _SUCCESS_OUTCOMES \
                or r.resulting_version != to_v:
            state["callback_defect"] = (
                state.get("callback_defect")
                or f"on_committed given a malformed result: {_safe_repr(r)}")
            return                          # do NOT touch a prior valid receipt
        if state.get("committed_established"):
            prior = state["facts"]
            if (prior.store_changed, prior.transaction_committed,
                    prior.resulting_version, str(prior)) != \
                    (r.store_changed, r.transaction_committed,
                     r.resulting_version, str(r)):
                state["callback_defect"] = "contradictory second on_committed"
            return                          # idempotent for an identical repeat
        state["facts"] = r
        state["committed_established"] = True
    return sink


def _open_result_problems(label, migrating, to_v, committed_facts) -> list:
    """The COMPLETE, mode-aware `OpenResult` contract (round 16, finding 3: v17
    checked SHAPE only, so `migrated`/¬changed/v1, a `created`/`adopted` in
    migrate mode, and `migrated`/v999 all passed and were then misreported as
    audit-storage failures). In migrate mode: `migrated` → changed+committed at
    `to_v`; `current` → (¬changed,¬committed) or (changed,committed) at `to_v`;
    `created`/`adopted` are FORBIDDEN. The result must also be consistent with
    any facts already delivered through `on_committed`."""
    if not _valid_open_result(label):
        return [f"malformed OpenResult: {_safe_repr(label)}"]
    branch = str(label)
    ch, co, ver = (label.store_changed, label.transaction_committed,
                   label.resulting_version)
    p = []
    if migrating:
        if branch in ("created", "adopted"):
            p.append(f"a dedicated migration must never {branch!r} a store")
        elif branch == "migrated":
            if not (ch is True and co is True and ver == to_v):
                p.append(f"migrated must be changed+committed at v{to_v}, "
                         f"got changed={ch} committed={co} v{ver}")
        elif branch == "current":
            if (ch, co) not in ((False, False), (True, True)) or ver != to_v:
                p.append(f"current must be (F,F) or (T,T) at v{to_v}, got "
                         f"changed={ch} committed={co} v{ver}")
    # Consistency with the facts on_committed already delivered, INCLUDING the
    # branch LABEL (round 16 f3 + round 17 f3: v18 compared only the change/
    # commit/version tuple, so a committed `migrated` returned as `current`
    # passed and the audit described a current-store repair — `migrated` and
    # `current-with-repair` are NOT interchangeable though their facts coincide).
    if committed_facts is not None and committed_facts is not label \
            and _valid_open_result(committed_facts) and (
                str(committed_facts), committed_facts.store_changed,
                committed_facts.transaction_committed,
                committed_facts.resulting_version) != (branch, ch, co, ver):
        p.append(f"the returned result {branch!r}/{ch}/{co}/v{ver} contradicts "
                 f"the on_committed branch {str(committed_facts)!r}")
    return p


def _store_path_problems(sp) -> list:
    """A stored/attested store path must be a CANONICAL absolute filesystem
    path: a string, no embedded NUL, filesystem-encodable, under the byte cap,
    and absolute (rounds 13–14 corrections A/B). Shared by the operation-row
    boundary and `MigrationAuditWriteError`, so both carriers reject the same
    malformed paths."""
    if not isinstance(sp, str):
        return [f"must be a string, is {type(sp).__name__}"]
    problems = []
    if "\x00" in sp:
        problems.append("contains an embedded NUL")   # os.fsencode/open reject it
    if not os.path.isabs(sp):
        problems.append("must be an absolute (canonical) path")
    try:
        encoded = os.fsencode(sp)
    except (UnicodeEncodeError, ValueError) as exc:
        problems.append(f"is not filesystem-encodable: {_safe_repr(exc)}")
    else:
        if len(encoded) > 4096:
            problems.append("exceeds 4096 bytes")
    return problems


