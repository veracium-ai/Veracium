# the older-row hooks and the two entry points (0013 §5b, §5d)

def _accepted_at(art, version: int) -> set:
    rec = art.get("schema_versions", {}).get(str(version), {})
    return {a.get("digest") for a in rec.get("accepted", [])
            if isinstance(a, dict)}


def _classify_source(art, conn, spath, found, objs, base) -> None:
    """The source must BE an accepted older manifestation before anything is
    said about migrating it — round 3 measured a stamped v1 store with an
    unauthorized extra table answering `migration-required`, which promises a
    migration path for a store that has none."""
    if sv.digest(objs, base) not in _accepted_at(art, base):
        raise sv.StoreVersionError(
            spath, found, sv.SCHEMA_VERSION, "stamped-shape-mismatch",
            diff=sv._shape_diff(objs, base))


def _refusing_hook(art):
    """Ordinary opening's older row: classify the source, then refuse.
    Ordinary opening cannot initiate migration — that is the offline boundary,
    stated as a mechanism."""
    def hook(conn, spath, found, objs, base):
        _classify_source(art, conn, spath, found, objs, base)
        raise MigrationRefused(
            "migration-required",
            f"store is schema v{base}; ordinary opening never migrates — "
            f"run the dedicated offline migration operation (§5b)")
    return hook


def _migrating_hook(art, authority):
    """The dedicated offline operation's older row: classify, check the
    authority, select the recorded path evidence, execute, compare the
    complete output against the record, and only then stamp. Every failure is
    a closed outcome; the kernel's transaction rolls anything partial back."""
    def hook(conn, spath, found, objs, base):
        _classify_source(art, conn, spath, found, objs, base)
        step = MIGRATIONS_DRAFT.get(base)
        if step is None or step.to_version != sv.SCHEMA_VERSION:
            # Adjacent single-step only; the skipped-release planner is
            # deferred to the first spec that needs two real steps.
            raise MigrationRefused(
                "migration-required",
                f"no adjacent declared step migrates v{base} to "
                f"v{sv.SCHEMA_VERSION}")
        probs = authority_problems(authority, spath, step,
                                   sv.digest(objs, base),
                                   snapshot=(art, _DRAFT["digest"]))
        if probs:
            raise MigrationRefused("migration-quiescence-required",
                                   "; ".join(probs))
        # Consumption happened at operation entry (round 5): by the time the
        # hook runs, this authority is already spent regardless of outcome.
        reg = validate_registry(current=sv.SCHEMA_VERSION)
        if reg:
            raise MigrationRefused("migration-evidence-missing",
                                   "the migration registry is malformed: "
                                   + "; ".join(reg))
        # Source rebuildable drift is repaired at the SOURCE version before
        # hashing, so the full-manifest comparison is against the accepted
        # source manifestation, not against incidental index drift.
        if sv.drift(objs, base):
            sv._repair_drift(conn, base)
            objs = manifest(conn)
            if sv.digest(objs, base) not in _accepted_at(art, base) \
                    or sv.drift(objs, base):
                raise sv.StoreVersionError(
                    spath, found, sv.SCHEMA_VERSION, "stamped-shape-mismatch",
                    diff=sv._shape_diff(objs, base))
        rec = _select_path_record(art, base, objs, step)
        try:
            apply_migration(conn, step)
        except (sqlite3.Error, RuntimeError) as exc:
            raise MigrationRefused("migration-failed", repr(exc)) from exc
        try:
            if sv.drift(manifest(conn), step.to_version):
                sv._repair_drift(conn, step.to_version)
            out_objs = manifest(conn)
        except (sqlite3.Error, RuntimeError) as exc:
            raise MigrationRefused("migration-failed", repr(exc)) from exc
        # The recorded prospective output authorises the stamp: complete
        # manifestation, acceptance digest AND full-manifest hash must all
        # match what the evidence job recorded (round 3, finding 2).
        if not (identity(out_objs) == rec["output_manifestation"]
                and sv.digest(out_objs, step.to_version)
                == rec["output_acceptance_digest"]
                and full_manifest_hash(out_objs)
                == rec["output_full_manifest_hash"]):
            raise MigrationRefused(
                "migration-result-mismatch",
                "the executed migration did not reproduce the recorded "
                "output manifestation; nothing was stamped")
        conn.execute(f"PRAGMA user_version = {step.to_version}")
    return hook


def _select_path_record(art, base, objs, step) -> dict:
    """Selection over RECORDED evidence, by the full key round 3 froze:
    runtime build identity × source version × source acceptance digest ×
    source full-manifest hash × destination version × migration declaration
    digest. Exactly one record or the migration does not run."""
    probs = path_evidence_problems(art) + expected_path_problems(art)
    if probs:
        raise MigrationRefused("migration-evidence-missing",
                               "; ".join(probs[:4]))
    me = sv.build_identity(sv.runtime_identity())
    want = (me, base, step.to_version, sv.digest(objs, base),
            full_manifest_hash(objs), migration_declaration_digest(step))
    hits = [r for r in art["paths"]
            if _algorithm_class(r) == "current"
            and _keyable_path_record(r) and _path_key(r) == want]
    if len(hits) != 1:
        raise MigrationRefused(
            "migration-evidence-missing",
            f"{len(hits)} recorded path-evidence records match this runtime, "
            f"source and migration declaration; a migration no recorded "
            f"evidence covers must not run")
    return hits[0]


def _source_missing_hook(conn, spath, found, objs):
    """The migrate-mode new-row seam (round 6): the dedicated operation must
    NEVER create — v7 measured `migrate_store` creating and stamping a fresh
    v2 store after the attested v1 source was deleted, and doing the same
    over an empty replacement database."""
    raise MigrationRefused(
        "migration-source-missing",
        f"the store at {spath!r} is empty; the authority attests an "
        f"existing source and a backup of it — a migration never creates")


def _migration_uri(canonical: str) -> str:
    """A mode=rw SQLite URI from the canonical path: opening it FAILS rather
    than creating a file, so a nonexistent target path stays nonexistent
    (round 6's regression list). Percent-encoding goes through the
    filesystem bytes, so surrogate-escaped names round-trip."""
    import urllib.parse
    return ("file:" + urllib.parse.quote(os.fsencode(canonical)) + "?mode=rw")


def _run(path, busy_timeout_ms: int, migrating: bool,
         authority=None) -> Outcome:
    """The terminal-audit wrapper (round 7, finding 3): once an operation is
    consumed, EVERY closed outcome — `migrated`, the no-op `current`, any
    refusal — writes its terminal event, so a spent authority with no record
    is impossible in the draft exactly as §5e requires of production. A
    terminal write failing raises the typed `MigrationAuditWriteError` with
    the committed flag."""
    state = {"consumed": False}
    out = _run_inner(path, busy_timeout_ms, migrating, authority, state)
    if migrating and state["consumed"]:
        committed = out == "migrated"
        try:
            _AUDIT.record(
                authority.operation_id,
                "migration_completed" if out in ("migrated", "current")
                else "migration_failed",
                {"outcome": str(out),
                 "occurred_at": datetime.now(timezone.utc).isoformat()})
        except Exception as exc:
            raise MigrationAuditWriteError(
                committed=committed,
                operation_id=authority.operation_id,
                store_path=authority.store_path,
                resulting_version=(authority.to_version if committed
                                   else authority.from_version),
                cause=exc)
    return out


def _run_inner(path, busy_timeout_ms: int, migrating: bool,
               authority, state) -> Outcome:
    # THE outermost boundary (rounds 5-7): parameter validation, path
    # conversion, canonicalization, the evidence SNAPSHOT, authority
    # validation, context entry, the connection and the planner all sit
    # inside it, with filesystem-encoding-aware conversions throughout.
    # Exactly two named classes escape (PackageConsistencyError,
    # MigrationAuditWriteError); anything else unforeseen is
    # `internal-error` — round 7: labelling an internal defect
    # `invalid-store` or `migration-failed` invited hosts to remediate a
    # healthy database.
    phase = "parameter-validation"
    try:
        if type(busy_timeout_ms) is not int or \
                not 0 < busy_timeout_ms <= 600_000:
            return Outcome("invalid-request",
                           f"busy_timeout_ms must be an int in 1..600000, "
                           f"got {_safe_repr(busy_timeout_ms)}")
        try:
            fs = os.fsdecode(os.fspath(path))
        except Exception as exc:
            return Outcome("invalid-request",
                           f"path is not path-like: {_safe_repr(exc)}")
        phase = "canonicalization"
        try:
            canonical = os.path.realpath(fs)
        except Exception as exc:
            return Outcome("store-unopenable", diagnostic=_safe_repr(exc))
        if len(os.fsencode(canonical)) > 4096:
            return Outcome("store-unopenable",
                           "canonical path exceeds 4096 bytes")
        # ONE evidence snapshot for the whole operation (round 7, finding 1):
        # digest and parse are of the same bytes, the authority is compared
        # against that digest, and the SAME parsed object enters the planner
        # context — nothing re-reads the path.
        phase = "evidence-snapshot"
        snapshot = _artifact_snapshot()
        if migrating:
            phase = "authority-validation"
            probs = authority_static_problems(authority, canonical,
                                              snapshot=snapshot)
            if probs:
                return Outcome("migration-quiescence-required",
                               diagnostic="; ".join(probs))
            res = _static_resolution_problems(authority, snapshot)
            if res:
                return Outcome("migration-evidence-missing",
                               diagnostic="; ".join(res))
            phase = "authority-consumption"
            try:
                _consume_authority(authority)
            except MigrationRefused as e:
                return Outcome(e.reason, diagnostic=e.diagnostic)
            state["consumed"] = True
            if not os.path.lexists(canonical):
                return Outcome(
                    "migration-source-missing",
                    f"no store exists at {canonical!r}; the authority "
                    f"attests an existing source — a migration never "
                    f"creates")
        phase = "context-entry"
        with _draft(loaded=snapshot) as art:
            try:
                phase = "runtime-gates"
                if not sv.runtime_supported():
                    return Outcome(
                        "unsupported-sqlite",
                        f"sqlite {sqlite3.sqlite_version} has no qualified "
                        f"schema-runtime record in the draft evidence; "
                        f"regenerate it here (migrations_0013.py "
                        f"--write-evidence)")
                if migrating and not migration_runtime_supported(art):
                    return Outcome(
                        "unsupported-sqlite",
                        "this runtime has no migration-confinement "
                        "qualification (or its recorded authorizer "
                        "behaviours do not reproduce here); migration "
                        "refuses before touching the store")
                hook = (_migrating_hook(art, authority) if migrating
                        else _refusing_hook(art))
                phase = "connect"
                try:
                    if migrating:
                        conn = sqlite3.connect(_migration_uri(canonical),
                                               uri=True,
                                               timeout=busy_timeout_ms / 1000)
                    else:
                        conn = sqlite3.connect(canonical,
                                               timeout=busy_timeout_ms / 1000)
                except sqlite3.Error as exc:
                    return Outcome("store-unopenable",
                                   diagnostic=_safe_repr(exc))
                conn.isolation_level = None
                phase = "planner"
                try:
                    conn.execute(
                        f"PRAGMA busy_timeout = {int(busy_timeout_ms)}")
                    label = sv.open_versioned(
                        conn, canonical,
                        allow_adopt=not migrating,   # a migration never adopts
                        older=hook,
                        new=_source_missing_hook if migrating else None)
                    return Outcome(label)
                finally:
                    conn.close()
            except sv.StoreVersionError as e:
                return Outcome(e.reason, diagnostic=e.diff)
            except MigrationRefused as e:
                return Outcome(e.reason, diagnostic=e.diagnostic)
            except sqlite3.DatabaseError as exc:
                return Outcome("invalid-store", diagnostic=_safe_repr(exc))
    except sv.PackageConsistencyError:
        raise                        # named escape 1 (§5d)
    except MigrationAuditWriteError:
        raise                        # named escape 2 (§5e)
    except _DraftContextMismatch as exc:
        return Outcome("migration-evidence-missing" if migrating
                       else "unsupported-sqlite",
                       diagnostic=_safe_repr(exc))
    except Exception as exc:
        # Round 7, finding 5: an unforeseen failure is a defect in THIS
        # library, not a property of the store and not a migration outcome —
        # labelling it invalid-store invited hosts to restore a healthy
        # database. `internal-error` is truthful: phase named, commit state
        # unknown unless the phase proves otherwise.
        return Outcome(
            "internal-error",
            diagnostic=f"phase={phase}; commit-state="
                       f"{'false' if phase != 'planner' else 'unknown'}; "
                       f"{_safe_repr(exc)}")


def open_or_migrate(path, busy_timeout_ms: int = 5000) -> Outcome:
    """Ordinary opening: the full inherited `0007` table, and the older row
    REFUSES — `migration-required` for an accepted older source, the ordinary
    shape reasons otherwise. No authority parameter exists here: the migration
    operation is not exposed through tenant-facing opening (round 3)."""
    return _run(path, busy_timeout_ms, migrating=False)


def migrate_store(path, authority: MigrationAuthority,
                  busy_timeout_ms: int = 5000) -> Outcome:
    """The dedicated offline migration operation (§5b): same planner, with the
    older row migrating under recorded evidence and an explicit, bound,
    exact-typed host attestation."""
    return _run(path, busy_timeout_ms, migrating=True, authority=authority)


