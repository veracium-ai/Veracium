def schema_evidence_problems(art) -> list:
    """The parts of the artifact that feed the `0007` kernel — draft accepted
    manifests, draft runtime records, legacy bases. Any problem here poisons
    the whole context (0007 round 12's rule: a malformed current record is
    evidence of tampering, and the safe reading is "unqualified").

    Must run under the draft registry patch: the validators it delegates to
    read the module registry."""
    if not isinstance(art, dict):
        return [f"artifact is {type(art).__name__}, not a mapping"]
    problems = []
    if set(art) != ARTIFACT_FIELDS:
        return [f"artifact fields {sorted(art)} are not exactly "
                f"{sorted(ARTIFACT_FIELDS)}"]
    # Round 5: exact scalar typing BEFORE equality — Python's coercive
    # equality accepted `True`, `13.0` and `2.0` for these (`True == 1`,
    # `13.0 == 13`), the same class 0007 round 13 closed for its own
    # revision fields. A numerically equal wrong-typed value is malformed.
    for f, want in (("migration_evidence_algorithm",
                     MIGRATION_EVIDENCE_ALGORITHM),
                    ("manifest_algorithm", sv.MANIFEST_ALGORITHM),
                    ("draft_schema_version", DRAFT_SCHEMA_VERSION)):
        v = art.get(f)
        if type(v) is not int or v != want:
            problems.append(f"artifact {f} must be exactly the int {want}, "
                            f"is {v!r} ({type(v).__name__})")
    if not isinstance(art.get("artifact"), str) or \
            art["artifact"] != "specs/0013 draft evidence":
        problems.append(f"artifact self-description is "
                        f"{art.get('artifact')!r}, not the expected string")
    ga = art.get("generated_at")
    if not isinstance(ga, str):
        problems.append(f"generated_at must be a string timestamp, is "
                        f"{type(ga).__name__}")
    else:
        try:
            if datetime.fromisoformat(ga).tzinfo is None:
                problems.append("generated_at must be timezone-aware")
        except ValueError:
            problems.append("generated_at does not parse as RFC 3339")
    gen = art.get("generator")
    if not isinstance(gen, dict) or set(gen) != {"tool", "repository_commit"} \
            or not all(isinstance(gen.get(k), str) and gen[k]
                       for k in ("tool", "repository_commit")):
        problems.append("generator must be {tool, repository_commit} with "
                        "nonempty strings — diagnostic provenance, not a "
                        "substitute for the declaration digest")
    versions = art.get("schema_versions")
    if not isinstance(versions, dict) or \
            set(versions) != {str(v) for v in SCHEMAS_DRAFT}:
        problems.append("schema_versions must cover exactly the draft registry")
    else:
        for v, rec in sorted(versions.items()):
            if not isinstance(rec, dict) or \
                    not isinstance(rec.get("accepted"), list) or \
                    not rec["accepted"]:
                problems.append(f"version {v}: no accepted manifests")
                continue
            for a in rec["accepted"]:
                if not isinstance(a, dict) or set(a) != {"digest", "objects",
                                                         "provenance"}:
                    problems.append(f"version {v}: accepted entry is not "
                                    f"exactly digest/objects/provenance")
                    continue
                # Round 4, finding 1: type-check BEFORE iterating — an
                # `objects: 1` here raised TypeError out of the validator, at
                # context entry, outside every exception mapping.
                if not isinstance(a["objects"], dict) or not all(
                        isinstance(k, str) for k in a["objects"]):
                    problems.append(f"version {v}: accepted objects is not a "
                                    f"string-keyed mapping")
                    continue
                if not isinstance(a["digest"], str) or \
                        not isinstance(a["provenance"], str):
                    problems.append(f"version {v}: accepted digest and "
                                    f"provenance must be strings")
                    continue
                problems += [f"version {v}: {p}" for p in
                             sv.manifestation_problems(a["objects"], int(v))]
                if sv._digest_of_identity(a["objects"], int(v)) != a["digest"]:
                    problems.append(f"version {v}: accepted objects do not "
                                    f"hash to their recorded digest")
    legacy = art.get("legacy_base_versions")
    if not isinstance(legacy, list) or \
            not all(type(v) is int and v in SCHEMAS_DRAFT for v in legacy):
        problems.append("legacy_base_versions must be declared draft versions")
    runtimes = art.get("runtimes")
    if not isinstance(runtimes, list):
        problems.append("runtimes must be a list")
    else:
        problems += sv.artifact_problems(runtimes)
        if not sv.active_records(runtimes):
            problems.append("no active runtime record; nothing is qualified")
    if not isinstance(art.get("migration_runtimes"), list):
        problems.append("migration_runtimes must be a list")
    if not isinstance(art.get("paths"), list):
        problems.append("paths must be a list")
    return problems


def path_record_problems(rec, art) -> list:
    """One §5c record: closed structure, and the record-level consistency
    rules round 3 required — the recorded output must hash to BOTH its
    recorded hashes, and the source identifiers must resolve to exactly one
    accepted source manifestation."""
    if not isinstance(rec, dict):
        return [f"path record is {type(rec).__name__}"]
    if set(rec) != PATH_RECORD_FIELDS:
        return [f"path record fields {sorted(rec)} are not exactly "
                f"{sorted(PATH_RECORD_FIELDS)}"]
    problems = []
    # Round 5: exact scalar typing here too — a path record carrying
    # `manifest_algorithm: 13.0` passed ordinary equality.
    if type(rec["manifest_algorithm"]) is not int or \
            rec["manifest_algorithm"] != sv.MANIFEST_ALGORITHM or \
            type(rec["migration_evidence_algorithm"]) is not int or \
            rec["migration_evidence_algorithm"] != MIGRATION_EVIDENCE_ALGORITHM:
        problems.append("path record algorithms must be exactly the current "
                        "ints")
    rt = rec["runtime"]
    if not isinstance(rt, dict) or \
            set(rt) != {"sqlite_version", "source_id", "features"} or \
            not isinstance(rt.get("sqlite_version"), str) or \
            not isinstance(rt.get("source_id"), str) or \
            not isinstance(rt.get("features"), dict):
        problems.append("path record runtime identity is malformed")
    else:
        # Round 4, finding 3: a path record's runtime must RESOLVE — to
        # exactly one active schema-runtime record and one valid current
        # migration-runtime record in this artifact. A foreign identity is an
        # unattested prospective record, not a spare.
        ident = sv.build_identity(rt)
        schema_hits = [r for r in sv.active_records(
            art.get("runtimes", []) if isinstance(art, dict) else [])
            if sv.build_identity(r) == ident]
        if len(schema_hits) != 1:
            problems.append(f"path record runtime resolves to "
                            f"{len(schema_hits)} active schema-runtime "
                            f"records, not exactly one")
        mig_rt = (art.get("migration_runtimes", [])
                  if isinstance(art, dict) else [])
        mig_hits = [r for r in mig_rt
                    if _algorithm_class(r) == "current"
                    and not migration_runtime_record_problems(r)
                    and sv.build_identity(r) == ident]
        if len(mig_hits) != 1:
            problems.append(f"path record runtime resolves to "
                            f"{len(mig_hits)} valid migration-runtime "
                            f"records, not exactly one")
    frm, to = rec["from_version"], rec["to_version"]
    if type(frm) is not int or type(to) is not int or to != frm + 1 or \
            frm not in SCHEMAS_DRAFT or to not in SCHEMAS_DRAFT:
        problems.append(f"path record step {frm!r}→{to!r} is not an adjacent "
                        f"declared pair")
        return problems
    for f in ("source_acceptance_digest", "source_full_manifest_hash",
              "output_acceptance_digest", "output_full_manifest_hash",
              "migration_declaration_digest", "provenance"):
        if not isinstance(rec[f], str) or not rec[f]:
            problems.append(f"path record field {f!r} must be a nonempty "
                            f"string")
    out = rec["output_manifestation"]
    if not isinstance(out, dict) or not all(isinstance(k, str) for k in out):
        problems.append("output_manifestation must be a string-keyed mapping")
        return problems
    problems += [f"output: {p}" for p in sv.manifestation_problems(out, to)]
    if sv._digest_of_identity(out, to) != rec["output_acceptance_digest"]:
        problems.append("recorded output does not hash to its recorded "
                        "acceptance digest")
    if full_manifest_hash(out) != rec["output_full_manifest_hash"]:
        problems.append("recorded output does not hash to its recorded "
                        "full-manifest hash")
    versions = art.get("schema_versions", {}) if isinstance(art, dict) else {}

    def _resolves(version: int, dig, fmh) -> int:
        vrec = versions.get(str(version), {})
        accepted = vrec.get("accepted", []) if isinstance(vrec, dict) else []
        return len([a for a in accepted if isinstance(a, dict)
                    and a.get("digest") == dig
                    and full_manifest_hash(a.get("objects", {})) == fmh])

    n = _resolves(frm, rec["source_acceptance_digest"],
                  rec["source_full_manifest_hash"])
    if n != 1:
        problems.append(f"source identifiers resolve to {n} accepted "
                        f"v{frm} manifestations, not exactly one")
    # Symmetric with the source rule: a migration output that is not an
    # accepted destination manifestation is exactly what 0007's accepted-SET
    # model exists to refuse — an evidenced-but-unaccepted output must fail at
    # the artifact, not at the stamp.
    n = _resolves(to, rec["output_acceptance_digest"],
                  rec["output_full_manifest_hash"])
    if n != 1:
        problems.append(f"output identifiers resolve to {n} accepted "
                        f"v{to} manifestations, not exactly one")
    return problems


def _path_key(rec) -> tuple:
    return (sv.build_identity(rec.get("runtime", {})), rec.get("from_version"),
            rec.get("to_version"), rec.get("source_acceptance_digest"),
            rec.get("source_full_manifest_hash"),
            rec.get("migration_declaration_digest"))


def _keyable_path_record(rec) -> bool:
    """Whether `_path_key` can be built and hashed — round 4's totality rule:
    type-check before hashing or set membership. A record failing this is
    already reported by the validators; it must not ALSO crash them."""
    return (isinstance(rec, dict)
            and isinstance(rec.get("runtime"), dict)
            and type(rec.get("from_version")) is int
            and type(rec.get("to_version")) is int
            and all(isinstance(rec.get(f), str) for f in
                    ("source_acceptance_digest", "source_full_manifest_hash",
                     "migration_declaration_digest")))


def path_evidence_problems(art) -> list:
    """Artifact-level: every current-algorithm path record valid — a missing
    or mistyped algorithm field is malformed, not superseded (round 4) — with
    no duplicate and no contradictory records under one selection key."""
    if not isinstance(art, dict) or not isinstance(art.get("paths"), list):
        return ["artifact has no path-record list"]
    problems, seen = [], {}
    for rec in art["paths"]:
        cls = _algorithm_class(rec)
        if cls == "superseded":
            continue                       # contributes nothing, poisons nothing
        if cls == "malformed":
            problems.append("path record with a missing or mistyped algorithm "
                            "field — malformed, not superseded")
            continue
        problems += path_record_problems(rec, art)
        if not _keyable_path_record(rec):
            continue                       # already reported; cannot be keyed
        key = _path_key(rec)
        if key in seen:
            if seen[key] != rec.get("output_full_manifest_hash"):
                problems.append("two path records share a selection key but "
                                "declare different outputs — the artifact is "
                                "self-contradictory and neither can be trusted")
            else:
                problems.append("duplicate path record for one selection key")
        seen[key] = rec.get("output_full_manifest_hash")
    return problems


def expected_path_problems(art) -> list:
    """Exact cardinality against the LIVE registry, ARTIFACT-WIDE (rounds 3
    and 4): the expected set is every active build identity × every declared
    step × every accepted source manifestation, and the actual current-record
    keys must equal it exactly. Round 4 measured a duplicated path with a
    foreign runtime identity passing — v5 computed expectations only for the
    process's own identity, so foreign, unattested prospective records could
    accumulate. An altered migration digests differently, so its expected
    pair has zero records — the round-3 self-authorization hole this closes."""
    if not isinstance(art, dict):
        return ["artifact is not a mapping"]
    problems = []
    identities = {sv.build_identity(r)
                  for r in sv.active_records(art.get("runtimes", []))}
    current = [r for r in art.get("paths", [])
               if _algorithm_class(r) == "current"]
    unsound = [r for r in current if not _keyable_path_record(r)]
    if unsound:
        problems.append(f"{len(unsound)} current path record(s) too "
                        f"malformed to key — reported by the record "
                        f"validator, counted here so cardinality stays exact")
    versions = art.get("schema_versions", {}) \
        if isinstance(art.get("schema_versions"), dict) else {}
    expected = set()
    for ident in identities:
        for frm, mig in sorted(MIGRATIONS_DRAFT.items()):
            src = versions.get(str(frm), {})
            for a in src.get("accepted", []) if isinstance(src, dict) else []:
                if not isinstance(a, dict):
                    continue
                expected.add((ident, frm, mig.to_version, a.get("digest"),
                              full_manifest_hash(a.get("objects", {})),
                              migration_declaration_digest(mig)))
    have = {}
    for r in current:
        if _keyable_path_record(r):
            have[_path_key(r)] = have.get(_path_key(r), 0) + 1
    for key in sorted(expected - set(have), key=repr):
        problems.append(f"no path-evidence record for expected combination "
                        f"(step {key[1]}→{key[2]})")
    for key in sorted(set(have) - expected, key=repr):
        problems.append(f"path-evidence record outside the expected set — "
                        f"foreign identity, undeclared step, or unaccepted "
                        f"source (step {key[1]}→{key[2]})")
    for key, n in sorted(have.items(), key=repr):
        if n > 1:
            problems.append(f"{n} path-evidence records for one combination")
    return problems


