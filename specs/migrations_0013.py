# evidence generation and verification (the M11/M12 draft forms)

def _repo_commit() -> str:
    """Diagnostic provenance for the generator field (round 5): which
    revision of the tooling produced the artifact. `unavailable` outside a
    git checkout (an extracted review archive) — provenance, never a
    substitute for the declaration digest."""
    import subprocess
    try:
        r = subprocess.run(["git", "rev-parse", "HEAD"], cwd=ROOT,
                           capture_output=True, text=True, timeout=10)
        return r.stdout.strip() if r.returncode == 0 and r.stdout.strip() \
            else "unavailable"
    except Exception:
        return "unavailable"


def _constructor_accepted(version: int) -> dict:
    c = sqlite3.connect(":memory:")
    for o in SCHEMAS_DRAFT[version]:
        c.execute(o.ddl)
    objs = identity(manifest(c))
    c.close()
    return {"digest": sv._digest_of_identity(objs, version), "objects": objs,
            "provenance": f"constructor v{version}"}


def _generate_artifact() -> tuple:
    """Build the prospective artifact by MEASURING this runtime: constructor
    manifestations, authorizer behaviours, and one executed migration per
    (declared step × accepted source). Returns (artifact, problems) — problems
    refuse generation, they are never written."""
    problems = []
    me = sv.runtime_identity()
    versions, legacy_src = {}, sv.legacy_base_versions
    with _registry():
        reg = validate_registry(current=sv.SCHEMA_VERSION)
        if reg:
            return None, [f"registry: {p}" for p in reg]
        for v in sorted(SCHEMAS_DRAFT):
            versions[str(v)] = {"accepted": [_constructor_accepted(v)]}
        runtime_rec = {
            **me, "manifest_algorithm": sv.MANIFEST_ALGORITHM,
            "schema_version": DRAFT_SCHEMA_VERSION,
            "constructor_digests": {
                str(v): versions[str(v)]["accepted"][0]["digest"]
                for v in SCHEMAS_DRAFT},
            "manifestations": {
                f"constructor v{v}": versions[str(v)]["accepted"][0]["objects"]
                for v in SCHEMAS_DRAFT},
        }
        problems += [f"runtime record: {p}"
                     for p in sv.runtime_record_problems(runtime_rec)]
        probes = authorizer_probes()
        mig_rec = {"sqlite_version": me["sqlite_version"],
                   "source_id": me["source_id"], "features": me["features"],
                   "migration_evidence_algorithm":
                       MIGRATION_EVIDENCE_ALGORITHM,
                   "authorizer_probes": probes}
        problems += [f"migration runtime: {p}"
                     for p in migration_runtime_record_problems(mig_rec)]
        paths = []
        for frm, mig in sorted(MIGRATIONS_DRAFT.items()):
            for a in versions[str(frm)]["accepted"]:
                c = sqlite3.connect(":memory:")
                c.isolation_level = None
                try:
                    for o in SCHEMAS_DRAFT[frm]:
                        c.execute(o.ddl)
                    c.execute("BEGIN IMMEDIATE")
                    apply_migration(c, mig)
                    if sv.drift(manifest(c), mig.to_version):
                        sv._repair_drift(c, mig.to_version)
                    out = identity(manifest(c))
                    c.execute("ROLLBACK")
                except (sqlite3.Error, RuntimeError) as exc:
                    problems.append(f"step {frm}: prospective execution "
                                    f"failed: {exc!r}")
                    continue
                finally:
                    c.close()
                paths.append({
                    "migration_evidence_algorithm":
                        MIGRATION_EVIDENCE_ALGORITHM,
                    "manifest_algorithm": sv.MANIFEST_ALGORITHM,
                    "runtime": {"sqlite_version": me["sqlite_version"],
                                "source_id": me["source_id"],
                                "features": me["features"]},
                    "from_version": frm, "to_version": mig.to_version,
                    "source_acceptance_digest": a["digest"],
                    "source_full_manifest_hash":
                        full_manifest_hash(a["objects"]),
                    "output_acceptance_digest":
                        sv._digest_of_identity(out, mig.to_version),
                    "output_full_manifest_hash": full_manifest_hash(out),
                    "output_manifestation": out,
                    "migration_declaration_digest":
                        migration_declaration_digest(mig),
                    "provenance": f"migrations_0013.py --write-evidence on "
                                  f"sqlite {me['sqlite_version']}",
                })
    art = {
        "artifact": "specs/0013 draft evidence",
        "migration_evidence_algorithm": MIGRATION_EVIDENCE_ALGORITHM,
        "manifest_algorithm": sv.MANIFEST_ALGORITHM,
        "draft_schema_version": DRAFT_SCHEMA_VERSION,
        "generated_at": canonical_timestamp(datetime.now(timezone.utc)),
        "generator": {"tool": "specs/migrations_0013.py",
                      "repository_commit": _repo_commit()},
        "schema_versions": versions,
        "legacy_base_versions": sorted(legacy_src()),
        "runtimes": [runtime_rec],
        "migration_runtimes": [mig_rec],
        "paths": paths,
    }
    with _registry():
        problems += [f"artifact: {p}" for p in schema_evidence_problems(art)]
        problems += [f"migration runtimes: {p}"
                     for p in migration_runtime_artifact_problems(art)]
        problems += [f"paths: {p}" for p in path_evidence_problems(art)]
        problems += [f"paths: {p}" for p in expected_path_problems(art)]
    return art, problems


@contextmanager
def _registry():
    """Registry-only patch (no evidence install) — for generation and
    verification, which measure the runtime rather than consult the file."""
    with _DRAFT_LOCK:
        assert _DRAFT["depth"] == 0, "generation inside an open draft context"
        saved = sv.SCHEMAS, sv.SCHEMA_VERSION
        sv.SCHEMAS = dict(SCHEMAS_DRAFT)
        sv.SCHEMA_VERSION = DRAFT_SCHEMA_VERSION
    try:
        yield
    finally:
        with _DRAFT_LOCK:
            sv.SCHEMAS, sv.SCHEMA_VERSION = saved


MIGRATION_EVIDENCE_REVISION_FIELDS = (
    "migration_evidence_algorithm", "manifest_algorithm",
    "draft_schema_version")
"""MigrationEvidenceRevision (round 5): the components that say which
GENERATION of tooling produced an artifact. Writes are monotone over this
tuple — an older checkout must never overwrite prospective evidence written
by newer migration, manifest or schema code. The same downgrade class 0007's
runtime-evidence writer already refuses."""


def _revision_components(art):
    """The existing artifact's revision, or None when unreadable."""
    if not isinstance(art, dict):
        return None
    vals = tuple(art.get(f) for f in MIGRATION_EVIDENCE_REVISION_FIELDS)
    return vals if all(type(v) is int for v in vals) else None


def _write_evidence_locked() -> int:
    # Monotone-revision refusal, WITH the inspection under the same
    # interprocess lock as publication (round 6: a pre-generation check was a
    # check-then-replace race — a future artifact published while an older
    # writer generated was downgraded, measured with a forced interleaving).
    # Round 5's rule stands: refuse
    # without changing a byte when any existing component exceeds this
    # tool's. Same-revision replacement is the explicit policy for the
    # single active runtime — regenerating on a new runner (the reviewer's
    # disposable-copy workflow) replaces the whole artifact at equal
    # revision. An unreadable existing revision also refuses: overwriting
    # what cannot be identified is not regeneration, it is data loss —
    # delete the file explicitly to start over.
    mine = (MIGRATION_EVIDENCE_ALGORITHM, sv.MANIFEST_ALGORITHM,
            DRAFT_SCHEMA_VERSION)
    if EVIDENCE_FILE.exists():
        existing = _revision_components(_artifact_snapshot()[0])
        if existing is None:
            print(f"refusing: {EVIDENCE_FILE} exists but its revision "
                  f"fields are unreadable; delete it explicitly to "
                  f"regenerate")
            return 1
        newer = [f"{name} {have} > {tool}" for name, have, tool
                 in zip(MIGRATION_EVIDENCE_REVISION_FIELDS, existing, mine)
                 if have > tool]
        if newer:
            print("refusing: the existing artifact was written by newer "
                  "tooling; nothing was changed:")
            for n in newer:
                print(f"  - {n}")
            return 1
    art, problems = _generate_artifact()
    if problems:
        print("refusing to record evidence; this runtime does not qualify:")
        for p in problems:
            print(f"  - {p}")
        return 1
    # Writer-unique staging (round 6: a fixed shared .tmp path is its own
    # concurrent-writer collision).
    tmp = EVIDENCE_FILE.with_name(
        f"{EVIDENCE_FILE.name}.{os.getpid()}-{uuid.uuid4().hex[:8]}.tmp")
    try:
        tmp.write_text(json.dumps(art, indent=1, sort_keys=True) + "\n")
        os.replace(tmp, EVIDENCE_FILE)
    finally:
        if tmp.exists():                      # v12's lesson: no stray .tmp
            tmp.unlink()
    print(f"recorded {EVIDENCE_FILE} for sqlite "
          f"{sqlite3.sqlite_version}: {len(art['paths'])} path record(s), "
          f"1 runtime, 1 migration-runtime qualification")
    return 0


def write_evidence() -> int:
    """The complete operation is serialized by an interprocess lock (round
    6): acquire, RE-read and validate the existing revision under the lock,
    generate, validate, stage to a writer-unique temporary, publish,
    release. The monotone inspection cannot race a concurrent publication
    because no publication happens outside the lock."""
    import fcntl
    lock_path = EVIDENCE_FILE.with_suffix(".lock")
    with open(lock_path, "w") as lockf:
        fcntl.flock(lockf, fcntl.LOCK_EX)
        try:
            return _write_evidence_locked()
        finally:
            fcntl.flock(lockf, fcntl.LOCK_UN)


def check_evidence() -> int:
    art = _artifact_snapshot()[0]
    if art is None:
        print(f"missing or unreadable {EVIDENCE_FILE.relative_to(ROOT)}")
        return 1
    with _registry():
        # Round 10, finding 5: every validator is independently total, but
        # `check_evidence` is a release gate — it wraps each so even an
        # unforeseen escape becomes a clean nonzero status, never a traceback.
        problems = []
        for validator in (schema_evidence_problems,
                          migration_runtime_artifact_problems,
                          path_evidence_problems, expected_path_problems):
            try:
                problems += validator(art)
            except Exception as exc:      # a validator must not, but the gate
                problems.append(          # never raises regardless
                    f"{validator.__name__} escaped on this artifact: "
                    f"{_safe_repr(exc)}")
        recorded = {sv.build_identity(r) for r in
                    sv.active_records(_artifact_list(art, "runtimes"))}
    if problems:
        for p in problems:
            print(f"  - {p}")
        return 1
    if sv.build_identity(sv.runtime_identity()) not in recorded:
        print(f"artifact records a different runtime identity than this "
              f"process (sqlite {sqlite3.sqlite_version}); structural checks "
              f"pass, re-derivation needs the recording runtime")
        return 2
    expected, gen_problems = _generate_artifact()
    if gen_problems:
        for p in gen_problems:
            print(f"  - regeneration: {p}")
        return 1
    drop = {"generated_at", "generator"}      # volatile provenance fields
    a = {k: v for k, v in art.items() if k not in drop}
    b = {k: v for k, v in expected.items() if k not in drop}
    if a != b:
        keys = [k for k in a if a.get(k) != b.get(k)]
        print(f"artifact does not reproduce on this runtime; differing "
              f"sections: {keys}")
        return 1
    print("evidence artifact reproduces exactly on this runtime")
    return 0


