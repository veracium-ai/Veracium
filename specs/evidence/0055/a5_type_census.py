#!/usr/bin/env python3
# Mutation-Matrix: tests/test_0055_carrier_boundaries.py::test_the_check_refuses_each_tampered_artifact
"""0055 round 5: the A5 TYPE CENSUS, per ARGUMENT (the write boundary; `carrier-boundaries.json` beside this file is
the per-CARRIER table). GENERATED by running, never written by hand.

THE ROWS are §2c-ii A5's rule read by `inspect`: every public `Memory` method, every parameter but `self`/`user_id`
whose annotation admits `str` (or has none). THE SCREEN of each row is read by `ast`: `own` (the method's own
`_cred_ingress(ids=..., free=...)`, or its I20 twin's), `callee:D3` (D3's `_d3_legacy_source_or_refuse`, reached
through `_source_revocation`), or none. One definition: the helpers are tests/test_0055_r4_closure.py's
(`_a5_rows`, `_screened_by`, `_run_a5`), which drive the same rows in the suite.

EACH ROW IS DRIVEN TWICE on a fresh store, with the token as `bytes` and as `str`, and records for each form: the
exception (or none), whether it is the type refusal (`ArgumentTypeRefused`, reason `not_a_string`), whether storage
is unchanged, the provider calls, where the token reached (storage, provider), and whether the exception's own text
carries the token. THE OUTCOME is
  `refused by type`       a screened row: bytes refused by type, before any provider call, storage unchanged, and
                          no token in the exception's text;
  `no further than str`   an unscreened row: bytes reach nothing str does not, and its exception carries the token
                          only where the str form's does (a library exception may carry the caller's own argument,
                          E1's library scope);
  `VIOLATION`             anything else (none at a current artifact: the suite drives the same assertions).

    $PY specs/evidence/0055/a5_type_census.py --check     # fast: the rows and screens, digests, the .md
    TMPDIR=/dev/shm $PY specs/evidence/0055/a5_type_census.py --write
"""
from __future__ import annotations

import hashlib
import importlib.util
import json
import pathlib
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[2]
JSON_OUT = HERE / "a5-type-census.json"
MD_OUT = HERE / "a5-type-census.md"
SELF = "specs/evidence/0055/a5_type_census.py"
HELPERS = ("tests/test_0055_r4_closure.py", "tests/test_0055_invariants.py", "specs/evidence/0055/vectors.py")
sys.path.insert(0, str(ROOT / "src"))


def _strict_pairs(pairs):
    """0026's evidence-boundary rule: a repeated key is a REFUSAL, never last-wins."""
    out = {}
    for k, v in pairs:
        if k in out:
            raise ValueError(f"duplicate key {k!r}")
        out[k] = v
    return out


def _closure():
    spec = importlib.util.spec_from_file_location("_0055_r4_closure_a5", ROOT / HELPERS[0])
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _src_digest() -> str:
    h = hashlib.sha256()
    files = sorted((ROOT / "src" / "veracium").rglob("*.py")) + [ROOT / SELF] + [ROOT / p for p in HELPERS]
    for f in files:
        h.update(f.relative_to(ROOT).as_posix().encode() + b"\0" + f.read_bytes() + b"\0")
    return h.hexdigest()


def census(C=None) -> list:
    """The rows and their screens, from the code (no run)."""
    C = C or _closure()
    return [{"method": m, "parameter": p, "screened_by": C._screened_by(m, p)} for m, p in C._a5_rows()]


def _form(C, exc, leak, unchanged, calls) -> dict:
    from veracium import credentials as cred
    return {"exception": type(exc).__name__ if exc is not None else None,
            "type_refusal": isinstance(exc, cred.ArgumentTypeRefused) and getattr(exc, "reason", None) == "not_a_string",
            "storage_unchanged": bool(unchanged), "provider_calls": calls, "reached": sorted(leak),
            "exception_text_carries_the_token": exc is not None and C.TOKEN in str(exc)}


def outcome(row: dict) -> str:
    b, s = row["bytes"], row["str"]
    if row["screened_by"]:
        ok = (b["type_refusal"] and b["storage_unchanged"] and b["provider_calls"] == 0 and not b["reached"]
              and not b["exception_text_carries_the_token"])
        return "refused by type" if ok else "VIOLATION"
    ok = (set(b["reached"]) <= set(s["reached"])
          and (not b["exception_text_carries_the_token"] or s["exception_text_carries_the_token"]))
    return "no further than str" if ok else "VIOLATION"


def measure() -> dict:
    C = _closure()
    rows = census(C)
    with tempfile.TemporaryDirectory(prefix="dev-a5-") as d:
        for i, r in enumerate(rows):
            for form in ("bytes", "str"):
                work = pathlib.Path(d) / f"r{i:03d}"
                work.mkdir(exist_ok=True)
                r[form] = _form(C, *C._run_a5(work, r["method"], r["parameter"], form))
            r["outcome"] = outcome(r)
    return {"about": "0055 round 5: the A5 type census, per argument (specs/evidence/0055/a5_type_census.py; the "
                     "module docstring defines every field)",
            "src_digest": _src_digest(), "rows": rows, "summary": summarize(rows)}


def summarize(rows: list) -> dict:
    by = {"own": 0, "callee:D3": 0, None: 0}
    for r in rows:
        by[r["screened_by"]] = by.get(r["screened_by"], 0) + 1
    return {"rows": len(rows), "methods": len({r["method"] for r in rows}),
            "screened_own": by["own"], "screened_callee_d3": by["callee:D3"], "unscreened": by[None],
            "refused_by_type": sum(r["outcome"] == "refused by type" for r in rows),
            "no_further_than_str": sum(r["outcome"] == "no further than str" for r in rows),
            "violations": sorted(f"{r['method']}.{r['parameter']}" for r in rows if r["outcome"] == "VIOLATION"),
            "unscreened_exception_echoes_in_both_forms": sum(
                1 for r in rows if not r["screened_by"] and r["bytes"]["exception_text_carries_the_token"]
                and r["str"]["exception_text_carries_the_token"])}


def render(doc: dict) -> str:
    s = doc["summary"]
    lines = ["# 0055: the A5 type census, per argument (generated; do not edit)", "",
             f"Generated by `{SELF} --write`; `--check` holds this file to the JSON beside it, the rows and screens to",
             "the code, and the measurement to the product's bytes. The module docstring defines every field. The",
             "per-carrier table is `carrier-boundaries.md`.", "",
             f"Rows: {s['rows']} over {s['methods']} methods. Screened by the method's own screen: {s['screened_own']}; "
             f"by D3 (a callee): {s['screened_callee_d3']}; unscreened: {s['unscreened']}. Refused by type: "
             f"{s['refused_by_type']}. No further than str: {s['no_further_than_str']}. Violations: "
             f"{len(s['violations'])}. Unscreened rows whose library exception carries the caller's own argument in "
             f"both forms (E1's library scope): {s['unscreened_exception_echoes_in_both_forms']}.", "",
             "| method | parameter | screen | bytes | str | outcome |", "|---|---|---|---|---|---|"]

    def form(f):
        bits = [f["exception"] or "returned"]
        if f["type_refusal"]:
            bits.append("type refusal")
        if f["reached"]:
            bits.append("reached " + "+".join(f["reached"]))
        if f["exception_text_carries_the_token"]:
            bits.append("text carries the token")
        return ", ".join(bits)
    for r in doc["rows"]:
        lines.append(f"| `{r['method']}` | `{r['parameter']}` | {r['screened_by'] or '-'} | {form(r['bytes'])} | "
                     f"{form(r['str'])} | {r['outcome']} |")
    return "\n".join(lines) + "\n"


def check() -> list:
    if not JSON_OUT.exists() or not MD_OUT.exists():
        return [f"missing: run {SELF} --write"]
    doc = json.loads(JSON_OUT.read_text(), object_pairs_hook=_strict_pairs)
    problems = []
    want = census()
    have = [{k: r[k] for k in ("method", "parameter", "screened_by")} for r in doc["rows"]]
    if want != have:
        problems.append(f"rows or screens differ from the code: "
                        f"{[w for w in want if w not in have][:3]} / {[h for h in have if h not in want][:3]}")
    if any(r["outcome"] != outcome(r) for r in doc["rows"]):
        problems.append("an outcome is not its row's measurement")
    if doc.get("src_digest") != _src_digest():
        problems.append("stale: the product, this script or its helpers changed since --write")
    if doc.get("summary") != summarize(doc["rows"]):
        problems.append("the summary is not the rows' summary")
    if MD_OUT.read_text() != render(doc):
        problems.append("the .md is not the JSON's rendering")
    return problems


def main(argv) -> int:
    if argv[1:] == ["--write"]:
        doc = measure()
        JSON_OUT.write_text(json.dumps(doc, indent=1, sort_keys=True) + "\n")
        # render what --check reads: the stored JSON, keys sorted
        doc = json.loads(JSON_OUT.read_text(), object_pairs_hook=_strict_pairs)
        MD_OUT.write_text(render(doc))
        print(json.dumps(doc["summary"], indent=1))
        return 0
    if argv[1:] == ["--check"]:
        problems = check()
        for p in problems:
            print("STALE:", p)
        if not problems:
            print("a5-type-census: current")
        return 1 if problems else 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
