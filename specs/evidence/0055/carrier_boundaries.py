def leaf_paths(model) -> list:
    """Every string leaf of a Pydantic model as (path, kind): `a.b` a nested field, `a[]` a list member, `a{key}` a
    dict key, `a{}` a dict value. `kind` is `str`, `enum`, `literal`, or the dict value's type name for a key."""
    from pydantic import BaseModel
    out: list = []

    def walk(tp, path, seen):
        origin, args = typing.get_origin(tp), typing.get_args(tp)
        if isinstance(tp, type) and issubclass(tp, BaseModel):
            if tp in seen:
                return
            # the RESOLVED annotation: a field whose type is defined later in its module (`Edge.last_outcome:
            # Optional[Outcome]`) holds a ForwardRef in `model_fields` until something rebuilds the model, so reading
            # `f.annotation` made the enumeration depend on import order (round 5: 506 rows alone, 512 in the suite)
            hints = typing.get_type_hints(tp)
            for name, f in tp.model_fields.items():
                walk(hints.get(name, f.annotation), f"{path}.{name}" if path else name, seen | {tp})
        elif origin in (list, tuple, set, frozenset):
            for a in args:
                if a is not Ellipsis:
                    walk(a, path + "[]", seen)
        elif origin is dict:
            vt = args[1] if len(args) > 1 else str
            out.append((path + "{key}", getattr(vt, "__name__", str(vt))))
            walk(vt, path + "{}", seen)
        elif origin is typing.Union or type(tp).__name__ == "UnionType":
            for a in args:
                if a is not type(None):
                    walk(a, path, seen)
        elif origin is typing.Literal:
            if any(isinstance(a, str) for a in args):
                out.append((path, "literal"))
        elif tp is str:
            out.append((path, "str"))
        elif isinstance(tp, type) and issubclass(tp, enum.Enum):
            out.append((path, "enum"))
    walk(model, "", frozenset())
    return sorted(set(out))


def side_columns(store) -> list:
    return sorted((t, c) for t, cols in store._credential_side_tables() for c in cols)


#: THE VALUE FORMS of a plant: the token alone, and the token behind an ISO-date prefix. Positions are not the whole
#: domain: a reader that compares a string lexically (`Episode.valid_now`) treats the bare token as a future date and
#: drops the record, so only the dated form reaches the wiki compile's episode line (round 5: a mutant unmasking that
#: line survived every bare plant).
FORMS = {"": lambda t: t, "@dated": lambda t: "2020-01-01 " + t}


def enumerate_rows(store=None) -> list:
    """The planting domain, as row ids (a position, then its value form), in a stable order."""
    return [pos + form for pos in _positions(store) for form in FORMS]


def _positions(store=None) -> list:
    from veracium.schema import Edge, Episode
    from veracium.store.sqlite import SqliteStore
    own = store is None
    if own:
        tmp = tempfile.TemporaryDirectory()
        store = SqliteStore(os.path.join(tmp.name, "enum.db"))
    try:
        rows = [f"side:{t}.{c}" for t, c in side_columns(store)]
    finally:
        if own:
            store.close()
            tmp.cleanup()
    for kind, model in (("edge", Edge), ("episode", Episode)):
        # an episode's journal is written only by a redaction, so its `journal` IS after one; an edge has both
        for where in ("current", "journal") + (("redacted-journal",) if kind == "edge" else ()):
            rows += [f"record:{kind}:{where}:{p}" for p, _k in leaf_paths(model)]
        rows.append(f"unparsed:{kind}")
    return rows


def declared_rows() -> list:
    from veracium import credential_finder as CF
    return ([{"row": f"declared:opaque:{name}", "declared": why} for name, why in CF.DECLARED_OPAQUE]
            + [{"row": f"declared:outside:{name}", "declared": "outside every remedy (OUTSIDE_REMEDY)"}
               for name in CF.OUTSIDE_REMEDY])


