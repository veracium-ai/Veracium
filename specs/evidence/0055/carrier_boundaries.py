def _set_path(doc, path: str, kind: str, token: str):
    """Write the token at `path` in a stored JSON document, creating what is absent (a legacy writer's shape)."""
    segs = re.findall(r"[^.\[\]{}]+|\[\]|\{key\}|\{\}", path)
    cur = doc
    for i, seg in enumerate(segs):
        last = i == len(segs) - 1
        nxt = segs[i + 1] if not last else None
        if seg == "[]":
            raise AssertionError("a list segment is handled by its parent")
        name = seg
        if nxt == "[]":
            if i + 1 == len(segs) - 1:
                cur[name] = [token]
                return
            cur[name] = [{}]
            cur = cur[name][0]
            segs.pop(i + 1)
            continue
        if nxt == "{key}":
            cur[name] = {token: 1 if kind == "int" else "x"}
            return
        if nxt == "{}":
            cur[name] = {"k": token}
            return
        if last:
            cur[name] = token
            return
        if not isinstance(cur.get(name), dict):
            cur[name] = {}
        cur = cur[name]


class _Emb:
    def __init__(self):
        self.seen: list = []

    def id(self):
        return "stub-embed-1"

    def dim(self):
        return 4

    def __call__(self, texts):
        self.seen.extend(texts)
        return [[1.0, 0.5, 0.25, 0.125] for _ in texts]


def _fill_for(con, table) -> dict:
    sql = con.execute("SELECT sql FROM sqlite_master WHERE name=?", (table,)).fetchone()[0]
    out = {}
    for col, members in re.findall(r"(\w+)\s+IN\s*\(([^)]*)\)", sql):
        first = members.split(",")[0].strip()
        out[col] = first.strip("'") if first.startswith("'") else int(first)
    return out


def _plant(con, row: str, token: str, ids: dict) -> dict:
    form = next(f for f in sorted(FORMS, key=len, reverse=True) if row.endswith(f))
    row, value = row[:len(row) - len(form)] if form else row, FORMS[form](token)
    return _plant_value(con, row, value, ids)


def _plant_value(con, row: str, token: str, ids: dict) -> dict:
    """Write the plant into the copied base store. A side-table column is rewritten in a REAL row the base's
    operations wrote, where the table has one (`plant: real row`); a table no base operation reaches gets one synthetic
    row (`plant: synthetic row`; its other columns are fillers, so a reader of that row may refuse it, and the row says
    so). Returns {"plant": ...} or {"refused": <the store's own refusal>}."""
    if row.startswith("side:"):
        table, col = row[5:].split(".", 1)
        real = con.execute(f"SELECT MIN(rowid) FROM {table} WHERE user_id='u'").fetchone()[0]
        try:
            if real is not None:
                con.execute(f"UPDATE {table} SET {col}=? WHERE rowid=?", (token, real))
                how = "real row"
            else:
                info = [c[1] for c in con.execute(f"PRAGMA table_info({table})")]
                fill = _fill_for(con, table)
                vals = {c: fill.get(c, f"x-{table}-{i}") for i, c in enumerate(info)}
                vals["user_id"] = "u"
                vals.update({c: ids[k] for c, k in (("edge_id", "edge"), ("episode_id", "episode")) if c in vals})
                vals[col] = token
                con.execute(f"INSERT INTO {table}({','.join(vals)}) VALUES ({','.join('?' * len(vals))})",
                            list(vals.values()))
                how = "synthetic row"
            con.commit()
        except sqlite3.IntegrityError as exc:
            con.rollback()
            return {"refused": f"IntegrityError: {exc}"}
        return {"plant": how}
    if row.startswith("unparsed:"):
        kind = row.split(":")[1]
        table = "edges" if kind == "edge" else "episodes"
        con.execute(f"UPDATE {table} SET json=? WHERE id=?", ("{not json " + token, ids[kind]))
        con.commit()
        return {"plant": "real row"}
    _r, kind, where, path = row.split(":", 3)
    from veracium.schema import Edge, Episode
    vkind = dict(leaf_paths(Edge if kind == "edge" else Episode))[path]
    if where == "current":
        table = "edges" if kind == "edge" else "episodes"
        rowid, text = con.execute(f"SELECT rowid, json FROM {table} WHERE id=?", (ids[kind],)).fetchone()
        doc = json.loads(text, object_pairs_hook=_strict_pairs)
        if path.startswith("agreement.") and not isinstance(doc.get("agreement"), dict):
            doc["agreement"] = {"markers": ["m"], "direction": "inbound", "lexicon": "v1"}   # a valid AgreementRecord
        _set_path(doc, path, vkind, token)
        cols = {c[1] for c in con.execute(f"PRAGMA table_info({table})")}
        sets = {"json": json.dumps(doc)}
        if path in cols:
            sets[path] = token         # a duplicate column (subject, relation, object, user_id, id) holds the same value
        con.execute(f"UPDATE {table} SET {', '.join(f'{k}=?' for k in sets)} WHERE rowid=?",
                    [*sets.values(), rowid])
    else:
        jtable, idcol = ("edge_event", "edge_id") if kind == "edge" else ("episode_event", "episode_id")
        rowid, text = con.execute(f"SELECT rowid, state FROM {jtable} WHERE {idcol}=? ORDER BY seq DESC LIMIT 1",
                                  (ids[f"{kind}_{where.replace('-', '_')}"],)).fetchone()
        doc = json.loads(text, object_pairs_hook=_strict_pairs)
        _set_path(doc, path, vkind, token)
        sets = {"state": json.dumps(doc)}
        if path == "user_id":
            sets["user_id"] = token
        con.execute(f"UPDATE {jtable} SET {', '.join(f'{k}=?' for k in sets)} WHERE rowid=?",
                    [*sets.values(), rowid])
    con.commit()
    return {"plant": "real row"}


def build_base(path: pathlib.Path, T) -> dict:
    """The store every plant starts from: one user's ordinary history, written by the product's own operations so
    the side tables hold real rows. Returns the ids the plants address."""
    from veracium import Memory, MemoryConfig
    from veracium.redaction import SOURCE_REVOCATION_REASONS
    from veracium.schema import Edge, Episode, EvidenceAuthor, Provenance, Volatility
    emb = _Emb()
    mem = Memory(llm=T.Stub(), embed=emb, config=_config(str(path)))
    try:
        target = T._seed_edge(mem, text="Denver")                 # the edge every record plant rewrites
        disputed, corrected, redacted = (T._seed_edge(mem, text=t) for t in ("Boulder", "Paris", "Rome"))
        mem.store.add_edge(Edge(id="e-cb-transient", user_id="u", subject="user", relation="feeling", object="tired",
                                volatility=Volatility.TRANSIENT,
                                provenance=Provenance(author_of_evidence=EvidenceAuthor.USER, evidence_ref="ev-cb-t",
                                                      source_id="chat")))
        prov = dict(author_of_evidence=EvidenceAuthor.USER, source_id="chat")
        # two COLD episodes in one partition, so maintain()'s consolidation runs and calls the provider
        for eid in ("ep-cb", "ep-cb-2"):
            mem.store.add_episode(Episode(id=eid, user_id="u", date="2020-01-01", summary="Ordinary episode " + eid,
                                          provenance=Provenance(evidence_ref="ev-" + eid, **prov)))
        mem.store.add_episode(Episode(id="ep-cb-j", user_id="u", date="2026-11-25", summary="Journalled episode",
                                      provenance=Provenance(evidence_ref="ev-cb-j", **prov)))
        mem.redact("u", episode_id="ep-cb-j", reason="operator_policy")   # an episode's journal row: redaction only
        mem.remember("u", "I work at Acme")
        mem.confirm("u", target.id, correlation_id="c-1")
        mem.reply("u", target.id, kind="context", text="more context", correlation_id="c-2")
        mem.dispute("u", disputed.id, reason="not true", actor="user")
        mem.correct("u", corrected.id, corrected_value="Lyon", actor="user")
        mem.redact("u", edge_id=redacted.id, reason="operator_policy")
        mem.revoke_source("u", None, "other-src", SOURCE_REVOCATION_REASONS[0])
        mem.embed_backfill("u")
        mem.recall("u", "where does the user live")              # compiles the wiki
        return {"edge": target.id, "edge_journal": target.id, "edge_redacted_journal": redacted.id,
                "episode": "ep-cb", "episode_journal": "ep-cb-j"}
    finally:
        mem.close()


def _config(db: str):
    from veracium import MemoryConfig
    return MemoryConfig(db_path=db, wiki_recompile_after_writes=1, consolidate_min_batch=2)


def _exit(fn, token: str, stub, emb, sink: dict, name: str, provider: dict):
    """Run one exit; record its RESULT's outcome in `sink` and the provider payloads it caused in `provider`."""
    p0, e0 = len(stub.prompts), len(emb.seen)
    try:
        out = fn()
        text = out if isinstance(out, str) else json.dumps(out, default=str)
        sink[name] = "LEAK" if token in text else "clean"
    except Exception as exc:                                   # noqa: BLE001 - the outcome is recorded
        sink[name] = f"raised {type(exc).__name__}"
    payload = [p for _role, p in stub.prompts[p0:]] + emb.seen[e0:]
    provider[name] = ("LEAK" if any(token in p for p in payload) else "clean") if payload else "no payload"


def measure_row(row: str, work: pathlib.Path, T, token: str, base: pathlib.Path, ids: dict) -> dict:
    import shutil
    from veracium import Memory, MemoryConfig, cli, credential_finder as CF
    from veracium.mcp_server import find_facts_impl, recall_impl
    from veracium import compile as _compile
    work.mkdir(parents=True)
    db = str(work / "m.db")
    shutil.copyfile(base, db)
    stub, emb = T.Stub(), _Emb()
    owner = (FORMS["@dated"](token) if row.endswith(":user_id@dated")
             else token if row.endswith(":user_id") else "u")   # a shaped user_id moves the record to that user
    rec: dict = {"row": row}
    con = sqlite3.connect(db)
    try:
        assert token not in T._dump(db), "the base store holds the token before the plant"
        got = _plant(con, row, token, ids)
    finally:
        con.close()
    if "refused" in got:
        rec["planted"] = False
        rec["refused"] = got["refused"]
        return rec
    rec["planted"] = True
    rec["plant"] = got["plant"]
    assert token in T._dump(db), row
    mem = Memory(llm=stub, embed=emb, config=_config(db))
    e_id = ids["edge"]
    try:
        hits = CF.scan(mem.store, None)
        rec["finder"] = sorted({f"{h.carrier} ({'removable' if h.removable else 'residual'})" for h in hits})
        served: dict = {}
        provider: dict = {}

        def lib_recall():
            r = mem.recall("u", "where does the user live", render_receipt=True)
            return {"context": r.context, "receipt": r.render_receipt}

        def briefing():
            r = mem.recall("u", render_receipt=True)
            return {"context": r.context, "receipt": r.render_receipt}

        def wiki():
            cached = _compile.ensure_wiki(mem.store, stub, "u", 1, mem.config.relations)   # the fresh-cache read
            compiled = _compile.compile_wiki(mem.store, stub, "u", mem.config.relations)    # the compile prompt
            return [cached, compiled]
        _exit(lib_recall, token, stub, emb, served, "library recall", provider)
        _exit(briefing, token, stub, emb, served, "library briefing", provider)
        _exit(lambda: mem.answer("u", "where does the user live"), token, stub, emb, served, "answer", provider)
        _exit(lambda: recall_impl(mem, "u", "where does the user live"), token, stub, emb, served, "MCP recall",
              provider)
        _exit(lambda: find_facts_impl(mem, "u", "where", capability="direct"), token, stub, emb, served,
              "MCP find_facts", provider)
        _exit(wiki, token, stub, emb, served, "wiki compile + fresh-cache read", provider)
        def embedder():
            if not row.startswith("side:edge_embedding."):
                mem.store._conn.execute("DELETE FROM edge_embedding WHERE user_id='u'")
                mem.store._conn.commit()
            return mem.embed_backfill("u")
        _exit(embedder, token, stub, emb, {}, "embedder (re-embeds every edge)", provider)
        _exit(lambda: mem.maintain("u"), token, stub, emb, {}, "maintain (consolidation)", provider)
        rec["served"] = served
        rec["provider"] = provider
        exp = work / "export.jsonl"
        try:
            mem.export_memory("u", str(exp))
            rec["export"] = "carries the token" if token in exp.read_text(errors="replace") else "no token"
        except Exception as exc:                               # noqa: BLE001 - recorded
            rec["export"] = f"raised {type(exc).__name__}"
        mem.close()
        mem = None
        rec["cli"] = {}
        for name, argv in (("credentials scan", ["credentials", "scan", "--db", db]),
                           ("why", ["why", "--db", db, "--user", "u", e_id]),
                           ("why --json", ["why", "--db", db, "--user", "u", "--json", e_id]),
                           ("why --find", ["why", "--db", db, "--user", "u", "--find", "Denver"]),
                           ("why --find --json", ["why", "--db", db, "--user", "u", "--json", "--find", "Denver"])):
            buf = io.StringIO()
            with contextlib.redirect_stdout(buf), contextlib.redirect_stderr(buf):
                try:
                    rc = cli.main(argv)
                except SystemExit as exc:
                    rc = exc.code
                except Exception as exc:                       # noqa: BLE001 - recorded; the text is checked too
                    buf.write(str(exc))
                    rc = f"raised {type(exc).__name__}"
            rec["cli"][name] = ("LEAK" if token in buf.getvalue()
                                else "clean" if rc in (0, 1) else rc if isinstance(rc, str) else f"exit {rc}")
        mem = Memory(llm=T.Stub(), config=MemoryConfig(db_path=db, wiki_recompile_after_writes=0))
        hits = CF.scan(mem.store, None)
        if hits and all(h.removable for h in hits):
            CF.act(mem, hits)
            how = "finder act"
        else:
            mem.forget(owner)
            how = "forget"
        left = CF.scan(mem.store, None)
        rec["remedy"] = f"{how}: " + ("gone" if not left and token not in T._dump(db)
                                      else f"REMAINS ({len(left)} hit(s) on re-scan, "
                                           f"token in db: {token in T._dump(db)})")
        return rec
    finally:
        if mem is not None:
            mem.close()


def measure() -> dict:
    T = _load("_0055_inv_cb", HELPERS[0])
    V = _load("_0055_vec_cb", HELPERS[1])
    token = V.GH
    rows = enumerate_rows()
    out = []
    with tempfile.TemporaryDirectory(prefix="dev-cb-") as d:
        base = pathlib.Path(d) / "base.db"
        ids = build_base(base, T)
        for i, row in enumerate(rows):
            out.append(measure_row(row, pathlib.Path(d) / f"r{i:04d}", T, token, base, ids))
    return {"about": "0055 round 5: the carrier-to-boundary coverage table, generated by planting "
                     "(specs/evidence/0055/carrier_boundaries.py; the module docstring defines every column)",
            "src_digest": _src_digest(), "rows": out, "declared": declared_rows(), "summary": summarize(out)}


def summarize(rows: list) -> dict:
    planted = [r for r in rows if r.get("planted")]
    leaks = sorted(f"{r['row']} -> {k}" for r in planted for col in ("served", "provider")
                   for k, v in r.get(col, {}).items() if v == "LEAK")
    leaks += sorted(f"{r['row']} -> cli {k}" for r in planted for k, v in r.get("cli", {}).items() if v == "LEAK")
    side = [r for r in rows if r["row"].startswith("side:")]
    return {"rows": len(rows), "planted": len(planted), "refused_by_the_store": len(rows) - len(planted),
            "side_table_rows": len(side),
            "side_real_row_plants": sum(1 for r in side if r.get("plant") == "real row"),
            "side_synthetic_row_plants": sum(1 for r in side if r.get("plant") == "synthetic row"),
            "side_refused": sum(1 for r in side if not r.get("planted")),
            "not_found": sorted(r["row"] for r in planted if not r.get("finder")),
            "remedy_not_gone": sorted(r["row"] for r in planted if not str(r.get("remedy", "")).endswith("gone")),
            "leaks": leaks,
            "export_carries_the_token": sum(1 for r in planted if r.get("export") == "carries the token")}


# ---- render, write, check -------------------------------------------------------------------------------------------

def render(doc: dict) -> str:
    s = doc["summary"]
    lines = ["# 0055: the carrier-to-boundary coverage table (generated; do not edit)", "",
             f"Generated by `{SELF} --write`; `--check` holds this file to the JSON beside it, the row set to the",
             "enumeration, and the measurement to the product's bytes. The module docstring defines every column.",
             "The write boundary is per argument: see `a5-type-census.md`.", "",
             f"Rows: {s['rows']} (planted {s['planted']}, refused by the store {s['refused_by_the_store']}). "
             f"Side-table rows: {s['side_table_rows']} (a real row rewritten {s['side_real_row_plants']}, a synthetic "
             f"row {s['side_synthetic_row_plants']}, refused {s['side_refused']}). "
             f"Not found by the finder: {len(s['not_found'])}. Remedy not complete: {len(s['remedy_not_gone'])}. "
             f"Leaks at a provider, served or CLI exit: {len(s['leaks'])}. "
             f"Export carries the token (recorded, not judged): {s['export_carries_the_token']}.", "",
             "| row | finder | provider | served | cli | export | remedy |", "|---|---|---|---|---|---|---|"]

    def cell(d):
        if not d:
            return "-"
        bad = [k for k, v in d.items() if v not in ("clean", "no payload")]
        return "clean" if not bad else "<br>".join(f"{k}: {d[k]}" for k in bad)
    for r in doc["rows"]:
        if not r.get("planted"):
            lines.append(f"| `{r['row']}` | refused by the store: {r['refused']} | | | | | |")
            continue
        lines.append(f"| `{r['row']}` | {'<br>'.join(r['finder']) or 'NOT FOUND'} | {cell(r['provider'])} | "
                     f"{cell(r['served'])} | {cell(r['cli'])} | {r['export']} | {r['remedy']} |")
    lines += ["", "## Declared, not planted", "", "| row | declared |", "|---|---|"]
    lines += [f"| `{d['row']}` | {d['declared']} |" for d in doc["declared"]]
    return "\n".join(lines) + "\n"


def check() -> list:
    """Problems with the committed artifacts, as sentences; empty when current."""
    if not JSON_OUT.exists() or not MD_OUT.exists():
        return [f"missing: run {SELF} --write"]
    doc = json.loads(JSON_OUT.read_text(), object_pairs_hook=_strict_pairs)
    problems = []
    want, have = enumerate_rows(), [r["row"] for r in doc["rows"]]
    # the enumeration must not depend on what this process imported first: compare a fresh interpreter's
    import subprocess
    fresh = subprocess.run([sys.executable, "-B", str(ROOT / SELF), "--enumerate"], capture_output=True, text=True,
                           cwd=str(ROOT))
    if fresh.returncode != 0 or json.loads(fresh.stdout, object_pairs_hook=_strict_pairs) != want:
        problems.append("the enumeration differs between this process and a fresh interpreter (import order)")
    if want != have:
        problems.append(f"row set differs from the enumeration: missing {sorted(set(want) - set(have))[:5]}, "
                        f"extra {sorted(set(have) - set(want))[:5]}, or reordered")
    if [d["row"] for d in doc["declared"]] != [d["row"] for d in declared_rows()]:
        problems.append("the declared rows differ from credential_finder's DECLARED_OPAQUE / OUTSIDE_REMEDY")
    if doc.get("src_digest") != _src_digest():
        problems.append(f"stale: the product, this script or its helpers changed since --write")
    if doc.get("summary") != summarize(doc["rows"]):
        problems.append("the summary is not the rows' summary")
    if MD_OUT.read_text() != render(doc):
        problems.append("the .md is not the JSON's rendering")
    return problems


def main(argv) -> int:
    if argv[1:] == ["--write"]:
        doc = measure()
        JSON_OUT.write_text(json.dumps(doc, indent=1, sort_keys=True) + "\n")
        # render what --check reads: the stored JSON, keys sorted
        doc = json.loads(JSON_OUT.read_text(), object_pairs_hook=_strict_pairs)
        MD_OUT.write_text(render(doc))
        print(json.dumps(doc["summary"], indent=1))
        return 0
    if argv[1:] == ["--enumerate"]:
        print(json.dumps(enumerate_rows()))
        return 0
    if argv[1:] == ["--check"]:
        problems = check()
        for p in problems:
            print("STALE:", p)
        if not problems:
            print("carrier-boundaries: current")
        return 1 if problems else 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
