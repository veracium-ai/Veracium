def _strict_pairs(pairs):
    """0026's evidence-boundary rule: a repeated key is a REFUSAL, never last-wins."""
    out = {}
    for k, v in pairs:
        if k in out:
            raise ValueError(f"duplicate key {k!r}")
        out[k] = v
    return out


def _load(name: str, rel: str):
    spec = importlib.util.spec_from_file_location(name, ROOT / rel)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _src_digest() -> str:
    """One digest over every file the measurement exercises: the whole product, this script and its helpers."""
    h = hashlib.sha256()
    files = sorted((ROOT / "src" / "veracium").rglob("*.py")) + [ROOT / SELF] + [ROOT / p for p in HELPERS]
    for f in files:
        h.update(f.relative_to(ROOT).as_posix().encode() + b"\0" + f.read_bytes() + b"\0")
    return h.hexdigest()


